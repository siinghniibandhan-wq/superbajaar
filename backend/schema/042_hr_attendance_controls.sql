-- 042: Configurable attendance geofences, maker-checker corrections and immutable audit.
-- Additive only. This migration does not seed attendance policy or location data.

CREATE TABLE IF NOT EXISTS public.hr_attendance_policies (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    establishment_id bigint NOT NULL REFERENCES public.hr_establishments(id) ON DELETE RESTRICT,
    grace_minutes integer NOT NULL DEFAULT 0 CHECK (grace_minutes BETWEEN 0 AND 240),
    break_minutes integer NOT NULL DEFAULT 0 CHECK (break_minutes BETWEEN 0 AND 720),
    geofence_enabled boolean NOT NULL DEFAULT false,
    geofence_enforced boolean NOT NULL DEFAULT false,
    require_location_on_clock_in boolean NOT NULL DEFAULT false,
    require_location_on_clock_out boolean NOT NULL DEFAULT false,
    effective_from date NOT NULL,
    effective_to date,
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    updated_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CHECK (NOT geofence_enforced OR geofence_enabled),
    CHECK (NOT require_location_on_clock_in OR geofence_enabled),
    CHECK (NOT require_location_on_clock_out OR geofence_enabled)
);
CREATE INDEX IF NOT EXISTS hr_attendance_policies_effective_idx
    ON public.hr_attendance_policies(establishment_id,effective_from,effective_to);

CREATE TABLE IF NOT EXISTS public.hr_attendance_work_locations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    establishment_id bigint NOT NULL REFERENCES public.hr_establishments(id) ON DELETE RESTRICT,
    code varchar(32) NOT NULL,
    name varchar(120) NOT NULL,
    latitude numeric(10,7) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude numeric(10,7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    radius_meters integer NOT NULL CHECK (radius_meters BETWEEN 10 AND 10000),
    is_active boolean NOT NULL DEFAULT true,
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(code)) > 0 AND length(trim(name)) > 0),
    UNIQUE(establishment_id,code)
);
CREATE INDEX IF NOT EXISTS hr_attendance_work_locations_active_idx
    ON public.hr_attendance_work_locations(establishment_id,is_active);

ALTER TABLE public.hr_attendance_sessions
    ADD COLUMN IF NOT EXISTS clock_in_latitude numeric(10,7),
    ADD COLUMN IF NOT EXISTS clock_in_longitude numeric(10,7),
    ADD COLUMN IF NOT EXISTS clock_in_accuracy_meters numeric(9,2),
    ADD COLUMN IF NOT EXISTS clock_in_work_location_id bigint REFERENCES public.hr_attendance_work_locations(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS clock_out_latitude numeric(10,7),
    ADD COLUMN IF NOT EXISTS clock_out_longitude numeric(10,7),
    ADD COLUMN IF NOT EXISTS clock_out_accuracy_meters numeric(9,2),
    ADD COLUMN IF NOT EXISTS clock_out_work_location_id bigint REFERENCES public.hr_attendance_work_locations(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS last_modified_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL;

ALTER TABLE public.hr_attendance_sessions
    ADD CONSTRAINT hr_attendance_clock_in_latitude_range
        CHECK (clock_in_latitude IS NULL OR clock_in_latitude BETWEEN -90 AND 90),
    ADD CONSTRAINT hr_attendance_clock_in_longitude_range
        CHECK (clock_in_longitude IS NULL OR clock_in_longitude BETWEEN -180 AND 180),
    ADD CONSTRAINT hr_attendance_clock_out_latitude_range
        CHECK (clock_out_latitude IS NULL OR clock_out_latitude BETWEEN -90 AND 90),
    ADD CONSTRAINT hr_attendance_clock_out_longitude_range
        CHECK (clock_out_longitude IS NULL OR clock_out_longitude BETWEEN -180 AND 180);

CREATE TABLE IF NOT EXISTS public.hr_attendance_correction_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_session_id bigint NOT NULL REFERENCES public.hr_attendance_sessions(id) ON DELETE RESTRICT,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    requested_clock_in_at timestamptz NOT NULL,
    requested_clock_out_at timestamptz,
    reason text NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','approved','rejected','cancelled')),
    requested_by_user_id bigint NOT NULL REFERENCES public.app_users(id) ON DELETE RESTRICT,
    reviewed_by_user_id bigint REFERENCES public.app_users(id) ON DELETE RESTRICT,
    review_note text,
    reviewed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (requested_clock_out_at IS NULL OR requested_clock_out_at >= requested_clock_in_at),
    CHECK (length(trim(reason)) >= 5),
    CHECK (reviewed_by_user_id IS NULL OR reviewed_by_user_id <> requested_by_user_id),
    CHECK ((status IN ('approved','rejected') AND reviewed_by_user_id IS NOT NULL AND reviewed_at IS NOT NULL)
        OR status NOT IN ('approved','rejected'))
);
CREATE UNIQUE INDEX IF NOT EXISTS hr_attendance_one_pending_correction_idx
    ON public.hr_attendance_correction_requests(attendance_session_id) WHERE status='pending';
CREATE INDEX IF NOT EXISTS hr_attendance_correction_review_idx
    ON public.hr_attendance_correction_requests(status,created_at DESC);

CREATE TABLE IF NOT EXISTS public.hr_attendance_audit_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_session_id bigint NOT NULL,
    employee_id bigint NOT NULL,
    event_type varchar(24) NOT NULL CHECK (event_type IN ('created','updated','deleted')),
    actor_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    before_state jsonb,
    after_state jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS hr_attendance_audit_session_idx
    ON public.hr_attendance_audit_events(attendance_session_id,created_at DESC);
CREATE INDEX IF NOT EXISTS hr_attendance_audit_employee_idx
    ON public.hr_attendance_audit_events(employee_id,created_at DESC);

CREATE OR REPLACE FUNCTION public.hr_attendance_write_audit_event()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_actor bigint;
    v_session_id bigint;
    v_employee_id bigint;
BEGIN
    IF TG_OP = 'DELETE' THEN
        v_actor := OLD.last_modified_by_user_id;
        v_session_id := OLD.id;
        v_employee_id := OLD.employee_id;
        INSERT INTO public.hr_attendance_audit_events
            (attendance_session_id,employee_id,event_type,actor_user_id,before_state)
        VALUES (v_session_id,v_employee_id,'deleted',v_actor,to_jsonb(OLD));
        RETURN OLD;
    ELSIF TG_OP = 'INSERT' THEN
        v_actor := COALESCE(NEW.last_modified_by_user_id,NEW.created_by_user_id);
        INSERT INTO public.hr_attendance_audit_events
            (attendance_session_id,employee_id,event_type,actor_user_id,after_state)
        VALUES (NEW.id,NEW.employee_id,'created',v_actor,to_jsonb(NEW));
        RETURN NEW;
    ELSE
        v_actor := COALESCE(NEW.last_modified_by_user_id,NEW.closed_by_user_id,OLD.last_modified_by_user_id);
        INSERT INTO public.hr_attendance_audit_events
            (attendance_session_id,employee_id,event_type,actor_user_id,before_state,after_state)
        VALUES (NEW.id,NEW.employee_id,'updated',v_actor,to_jsonb(OLD),to_jsonb(NEW));
        RETURN NEW;
    END IF;
END $$;

DROP TRIGGER IF EXISTS hr_attendance_audit_trigger ON public.hr_attendance_sessions;
CREATE TRIGGER hr_attendance_audit_trigger
    AFTER INSERT OR UPDATE OR DELETE ON public.hr_attendance_sessions
    FOR EACH ROW EXECUTE FUNCTION public.hr_attendance_write_audit_event();

CREATE OR REPLACE FUNCTION public.hr_attendance_audit_immutable()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'HR attendance audit events are immutable';
END $$;
DROP TRIGGER IF EXISTS hr_attendance_audit_no_update ON public.hr_attendance_audit_events;
CREATE TRIGGER hr_attendance_audit_no_update
    BEFORE UPDATE OR DELETE ON public.hr_attendance_audit_events
    FOR EACH ROW EXECUTE FUNCTION public.hr_attendance_audit_immutable();
