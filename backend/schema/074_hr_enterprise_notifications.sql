-- 074: durable in-app notifications for employee document, certificate and asset expiries.
CREATE TABLE IF NOT EXISTS public.hr_enterprise_notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    record_id bigint NOT NULL REFERENCES public.hr_enterprise_records(id) ON DELETE RESTRICT,
    notification_type text NOT NULL CHECK (notification_type IN ('due_soon','overdue')),
    title text NOT NULL CHECK (length(trim(title)) > 0),
    message text NOT NULL CHECK (length(trim(message)) > 0),
    due_date date NOT NULL,
    status text NOT NULL DEFAULT 'unread' CHECK (status IN ('unread','read')),
    created_at timestamptz NOT NULL DEFAULT now(),
    read_at timestamptz,
    UNIQUE(employee_id,record_id,notification_type),
    CHECK ((status='unread' AND read_at IS NULL) OR (status='read' AND read_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS hr_enterprise_notifications_employee_idx
    ON public.hr_enterprise_notifications(employee_id,status,created_at DESC);
