-- Private proof files are stored in the existing private S3 bucket.
-- PostgreSQL stores metadata and object keys only; no document bytes or public URLs.
CREATE TABLE IF NOT EXISTS public.identity_verification_documents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id bigint NOT NULL REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    uploaded_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    document_type text NOT NULL CHECK (document_type IN
        ('identity_proof','address_proof','business_proof','other')),
    object_key text NOT NULL UNIQUE,
    content_type text NOT NULL CHECK (content_type IN
        ('application/pdf','image/jpeg','image/png')),
    file_size_bytes bigint NOT NULL CHECK (file_size_bytes BETWEEN 1 AND 10485760),
    sha256_hex char(64) NOT NULL,
    status text NOT NULL DEFAULT 'pending_review'
        CHECK (status IN ('pending_review','accepted','rejected','withdrawn')),
    reviewed_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    review_reason text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((status IN ('accepted','rejected') AND reviewed_at IS NOT NULL
            AND reviewed_by_user_id IS NOT NULL AND length(trim(COALESCE(review_reason,''))) >= 5)
        OR status NOT IN ('accepted','rejected'))
);

CREATE INDEX IF NOT EXISTS identity_verification_documents_party_idx
    ON public.identity_verification_documents(party_id,created_at DESC);

