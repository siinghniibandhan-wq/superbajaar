-- 046: Additive storage for short-lived identity verification challenges.
-- OTP values are never stored; only keyed digests are persisted by the application.
-- Provider credentials remain environment configuration, not database schema.

CREATE TABLE IF NOT EXISTS public.identity_otp_challenges (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_token text NOT NULL UNIQUE,
    purpose text NOT NULL CHECK (purpose IN ('identity_link','contact_verification')),
    channel text NOT NULL CHECK (channel IN ('email','sms','whatsapp','telegram')),
    contact_type text NOT NULL CHECK (contact_type IN ('email','phone')),
    normalized_contact text NOT NULL,
    otp_digest text NOT NULL,
    requester_party_id bigint REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    target_party_id bigint REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    requested_profile_type text CHECK (
        requested_profile_type IS NULL OR requested_profile_type IN
        ('customer_account','crm_customer','employee','vendor_organisation')
    ),
    requested_source_id bigint,
    requested_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    attempts smallint NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    max_attempts smallint NOT NULL DEFAULT 5 CHECK (max_attempts BETWEEN 1 AND 10),
    expires_at timestamptz NOT NULL,
    verified_at timestamptz,
    consumed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (expires_at > created_at),
    CHECK (verified_at IS NULL OR verified_at <= expires_at),
    CHECK (consumed_at IS NULL OR verified_at IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS identity_otp_challenges_active_contact_idx
    ON public.identity_otp_challenges(contact_type, normalized_contact, created_at DESC)
    WHERE consumed_at IS NULL;

CREATE INDEX IF NOT EXISTS identity_otp_challenges_expiry_idx
    ON public.identity_otp_challenges(expires_at)
    WHERE consumed_at IS NULL;

CREATE INDEX IF NOT EXISTS identity_otp_challenges_target_idx
    ON public.identity_otp_challenges(target_party_id, requested_profile_type, requested_source_id)
    WHERE consumed_at IS NULL;

