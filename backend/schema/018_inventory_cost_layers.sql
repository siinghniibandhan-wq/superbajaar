-- Opening-stock layers require an explicit, auditable valuation and are linked to
-- their opening adjustment movement; never derive them from current catalogue cost.
CREATE TABLE IF NOT EXISTS public.inventory_order_issues (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE RESTRICT,
    order_line_id bigint NOT NULL REFERENCES public.order_lines(id) ON DELETE RESTRICT,
    movement_id bigint NOT NULL UNIQUE REFERENCES public.inventory_movements(id) ON DELETE RESTRICT,
    location_id bigint NOT NULL REFERENCES public.stock_locations(id) ON DELETE RESTRICT,
    fulfilment_reference text NOT NULL UNIQUE,
    quantity numeric(14,3) NOT NULL CHECK (quantity > 0),
    total_cost numeric(16,2) NOT NULL CHECK (total_cost >= 0),
    allocation_method text NOT NULL DEFAULT 'fifo' CHECK (allocation_method IN ('fifo','fefo')),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(fulfilment_reference)) > 0)
);

CREATE INDEX IF NOT EXISTS inventory_order_issues_order_idx
    ON public.inventory_order_issues (order_id, order_line_id);


CREATE OR REPLACE FUNCTION public.inventory_protect_order_issue()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Fulfilment stock issue records are immutable; use a return or reversal workflow';
END;
$$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'inventory_cost_layers_protect_trg' AND tgrelid = 'public.inventory_cost_layers'::regclass) THEN
        CREATE TRIGGER inventory_cost_layers_protect_trg
        BEFORE UPDATE OR DELETE ON public.inventory_cost_layers
        FOR EACH ROW EXECUTE FUNCTION public.inventory_protect_cost_layer();
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'inventory_cost_allocations_protect_trg' AND tgrelid = 'public.inventory_cost_allocations'::regclass) THEN
        CREATE TRIGGER inventory_cost_allocations_protect_trg
        BEFORE UPDATE OR DELETE ON public.inventory_cost_allocations
        FOR EACH ROW EXECUTE FUNCTION public.inventory_protect_cost_allocation();
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'inventory_order_issues_protect_trg' AND tgrelid = 'public.inventory_order_issues'::regclass) THEN
        CREATE TRIGGER inventory_order_issues_protect_trg
        BEFORE UPDATE OR DELETE ON public.inventory_order_issues
        FOR EACH ROW EXECUTE FUNCTION public.inventory_protect_order_issue();
    END IF;
END
$$;



