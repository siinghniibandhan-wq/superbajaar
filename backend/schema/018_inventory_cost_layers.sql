-- A GRN line may create cost layers only up to the quantity formally accepted
-- by QC. The deferred check allows QC disposition and layer creation in one
-- transaction while preventing quarantined/rejected goods from becoming saleable.
CREATE OR REPLACE FUNCTION public.inventory_check_grn_accepted_cost_layers()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    accepted numeric(14,3);
    costed numeric(14,3);
BEGIN
    IF NEW.goods_receipt_line_id IS NULL THEN
        RETURN NULL;
    END IF;
    SELECT accepted_quantity INTO accepted
      FROM public.goods_receipt_lines
     WHERE id = NEW.goods_receipt_line_id;
    SELECT COALESCE(sum(received_quantity),0) INTO costed
      FROM public.inventory_cost_layers
     WHERE goods_receipt_line_id = NEW.goods_receipt_line_id;
    IF accepted IS NULL OR costed > accepted THEN
        RAISE EXCEPTION 'Costed GRN quantity % exceeds QC-accepted quantity % for GRN line %',
            costed, COALESCE(accepted,0), NEW.goods_receipt_line_id;
    END IF;
    RETURN NULL;
END;
$$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'inventory_grn_accepted_cost_layers_trg'
          AND tgrelid = 'public.inventory_cost_layers'::regclass
    ) THEN
        CREATE CONSTRAINT TRIGGER inventory_grn_accepted_cost_layers_trg
        AFTER INSERT ON public.inventory_cost_layers
        DEFERRABLE INITIALLY DEFERRED
        FOR EACH ROW EXECUTE FUNCTION public.inventory_check_grn_accepted_cost_layers();
    END IF;
END
$$;

