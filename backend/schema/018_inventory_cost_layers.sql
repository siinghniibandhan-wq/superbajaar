-- Inventory cost layers and issue allocations (migration 018; depends on Purchasing 017).
-- One receipt movement creates one immutable receipt cost layer. Remaining quantity is
-- reduced only by locked, persisted allocations. Expiry belongs to the received batch.
CREATE TABLE IF NOT EXISTS public.inventory_cost_layers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id bigint NOT NULL REFERENCES public.product_variants(id) ON DELETE RESTRICT,
    location_id bigint NOT NULL REFERENCES public.stock_locations(id) ON DELETE RESTRICT,
    receipt_movement_id bigint NOT NULL REFERENCES public.inventory_movements(id) ON DELETE RESTRICT,
    purchase_order_line_id bigint REFERENCES public.purchase_order_lines(id) ON DELETE RESTRICT,
    goods_receipt_line_id bigint REFERENCES public.goods_receipt_lines(id) ON DELETE RESTRICT,
    source_layer_id bigint REFERENCES public.inventory_cost_layers(id) ON DELETE RESTRICT,
    batch_code text,
    expiry_date date,
    received_quantity numeric(14,3) NOT NULL CHECK (received_quantity > 0),
    remaining_quantity numeric(14,3) NOT NULL CHECK (remaining_quantity >= 0 AND remaining_quantity <= received_quantity),
    unit_cost numeric(14,4) NOT NULL CHECK (unit_cost >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (batch_code IS NULL OR length(trim(batch_code)) > 0)
);

-- A transfer-in movement can preserve multiple source lots. Ordinary receipts remain
-- one layer per movement; transfer layers are unique per source layer.
CREATE UNIQUE INDEX IF NOT EXISTS inventory_cost_layers_receipt_movement_once_idx
    ON public.inventory_cost_layers (receipt_movement_id)
    WHERE source_layer_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS inventory_cost_layers_transfer_source_once_idx
    ON public.inventory_cost_layers (receipt_movement_id, source_layer_id)
    WHERE source_layer_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS inventory_cost_layers_grn_line_idx
    ON public.inventory_cost_layers (goods_receipt_line_id)
    WHERE goods_receipt_line_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS inventory_cost_layers_fifo_idx
    ON public.inventory_cost_layers (variant_id, location_id, created_at, id)
    WHERE remaining_quantity > 0;
CREATE INDEX IF NOT EXISTS inventory_cost_layers_fefo_idx
    ON public.inventory_cost_layers (variant_id, location_id, expiry_date, created_at, id)
    WHERE remaining_quantity > 0;

CREATE TABLE IF NOT EXISTS public.inventory_cost_allocations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_movement_id bigint NOT NULL REFERENCES public.inventory_movements(id) ON DELETE RESTRICT,
    cost_layer_id bigint NOT NULL REFERENCES public.inventory_cost_layers(id) ON DELETE RESTRICT,
    quantity numeric(14,3) NOT NULL CHECK (quantity > 0),
    unit_cost numeric(14,4) NOT NULL CHECK (unit_cost >= 0),
    total_cost numeric(16,2) NOT NULL CHECK (total_cost >= 0 AND total_cost = round(quantity*unit_cost,2)),
    allocation_method text NOT NULL DEFAULT 'fifo' CHECK (allocation_method IN ('fifo','fefo')),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (issue_movement_id, cost_layer_id)
);
CREATE INDEX IF NOT EXISTS inventory_cost_allocations_layer_idx
    ON public.inventory_cost_allocations (cost_layer_id);




-- Deferred cross-table invariant: every reduction in remaining layer quantity must
-- have matching immutable allocation rows by the end of the transaction.
CREATE OR REPLACE FUNCTION public.inventory_check_cost_layer_allocation_balance()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    layer_key bigint;
    expected_allocated numeric(14,3);
    actual_allocated numeric(14,3);
BEGIN
    IF TG_TABLE_NAME = 'inventory_cost_layers' THEN
        layer_key := NEW.id;
    ELSE
        layer_key := NEW.cost_layer_id;
    END IF;

    SELECT received_quantity - remaining_quantity
      INTO expected_allocated
      FROM public.inventory_cost_layers
     WHERE id = layer_key;

    IF expected_allocated IS NULL THEN
        RETURN NULL;
    END IF;

    SELECT COALESCE(sum(quantity),0)
      INTO actual_allocated
      FROM public.inventory_cost_allocations
     WHERE cost_layer_id = layer_key;

    IF actual_allocated <> expected_allocated THEN
        RAISE EXCEPTION 'Cost layer % has allocated quantity %, expected %',
            layer_key, actual_allocated, expected_allocated;
    END IF;
    RETURN NULL;
END;
$$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'inventory_cost_layer_allocation_balance_trg'
          AND tgrelid = 'public.inventory_cost_layers'::regclass
    ) THEN
        CREATE CONSTRAINT TRIGGER inventory_cost_layer_allocation_balance_trg
        AFTER UPDATE ON public.inventory_cost_layers
        DEFERRABLE INITIALLY DEFERRED
        FOR EACH ROW EXECUTE FUNCTION public.inventory_check_cost_layer_allocation_balance();
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'inventory_cost_allocation_balance_trg'
          AND tgrelid = 'public.inventory_cost_allocations'::regclass
    ) THEN
        CREATE CONSTRAINT TRIGGER inventory_cost_allocation_balance_trg
        AFTER INSERT ON public.inventory_cost_allocations
        DEFERRABLE INITIALLY DEFERRED
        FOR EACH ROW EXECUTE FUNCTION public.inventory_check_cost_layer_allocation_balance();
    END IF;
END
$$;

-- Cost-layer identity and source valuation are immutable. Remaining quantity can only fall.
CREATE OR REPLACE FUNCTION public.inventory_protect_cost_layer()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Inventory cost layers cannot be deleted; use a stock issue or reversal';
    END IF;
    IF NEW.variant_id IS DISTINCT FROM OLD.variant_id
       OR NEW.location_id IS DISTINCT FROM OLD.location_id
       OR NEW.receipt_movement_id IS DISTINCT FROM OLD.receipt_movement_id
       OR NEW.purchase_order_line_id IS DISTINCT FROM OLD.purchase_order_line_id
       OR NEW.source_layer_id IS DISTINCT FROM OLD.source_layer_id
       OR NEW.batch_code IS DISTINCT FROM OLD.batch_code
       OR NEW.expiry_date IS DISTINCT FROM OLD.expiry_date
       OR NEW.received_quantity IS DISTINCT FROM OLD.received_quantity
       OR NEW.unit_cost IS DISTINCT FROM OLD.unit_cost
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'Inventory cost layer source and valuation fields are immutable';
    END IF;
    IF NEW.remaining_quantity > OLD.remaining_quantity THEN
        RAISE EXCEPTION 'Inventory cost layer quantity cannot be increased; create a new receipt layer';
    END IF;
    RETURN NEW;
END;
$$;

