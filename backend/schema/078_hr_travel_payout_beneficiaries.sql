-- 078: tokenized employee payout beneficiaries and external travel payout references.
CREATE TABLE IF NOT EXISTS public.hr_employee_payout_beneficiaries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
 provider_name text NOT NULL,
 beneficiary_reference text NOT NULL,
 currency char(3) NOT NULL DEFAULT 'INR',
 status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','verified','disabled')),
 created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
 verified_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
 verified_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK(length(trim(provider_name))>0 AND length(trim(beneficiary_reference))>0),
 CHECK((status='verified' AND verified_by_user_id IS NOT NULL AND verified_at IS NOT NULL) OR status<>'verified'),
 UNIQUE(employee_id,provider_name)
);
CREATE INDEX IF NOT EXISTS hr_employee_payout_beneficiaries_lookup_idx
 ON public.hr_employee_payout_beneficiaries(employee_id,status,provider_name);
ALTER TABLE public.hr_travel_advance_disbursements
 ADD COLUMN IF NOT EXISTS provider_name text,
 ADD COLUMN IF NOT EXISTS provider_payout_reference text,
 ADD COLUMN IF NOT EXISTS provider_payout_status text;
CREATE UNIQUE INDEX IF NOT EXISTS hr_travel_advance_provider_payout_uq
 ON public.hr_travel_advance_disbursements(provider_name,provider_payout_reference)
 WHERE provider_payout_reference IS NOT NULL;
