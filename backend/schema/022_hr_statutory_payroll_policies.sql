-- Configurable, effective-dated statutory payroll policy foundation.
-- No statutory rates or jurisdiction defaults are seeded by this migration.
CREATE TABLE IF NOT EXISTS public.hr_establishments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    legal_name text NOT NULL,
    display_name text NOT NULL,
    state_code char(2) NOT NULL,
    country_code char(2) NOT NULL DEFAULT 'IN',
    address jsonb NOT NULL DEFAULT '{}'::jsonb,
    registrations jsonb NOT NULL DEFAULT '{}'::jsonb,
    is_active boolean NOT NULL DEFAULT true,
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(code)) > 0),
    CHECK (length(trim(legal_name)) > 0),
    CHECK (length(trim(display_name)) > 0),
    CHECK (state_code ~ '^[A-Z]{2}$'),
    CHECK (country_code = 'IN'),
    CHECK (jsonb_typeof(address) = 'object'),
    CHECK (jsonb_typeof(registrations) = 'object')
);

CREATE TABLE IF NOT EXISTS public.hr_employee_statutory_profiles (
    employee_id bigint PRIMARY KEY REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    establishment_id bigint NOT NULL REFERENCES public.hr_establishments(id) ON DELETE RESTRICT,
    uan text,
    esic_number text,
    pan text,
    pf_applicable_override boolean,
    esi_applicable_override boolean,
    pt_applicable_override boolean,
    override_reason text,
    tds_regime text CHECK (tds_regime IS NULL OR tds_regime IN ('old','new')),
    declarations jsonb NOT NULL DEFAULT '{}'::jsonb,
    exemptions jsonb NOT NULL DEFAULT '{}'::jsonb,
    previous_employer_income jsonb NOT NULL DEFAULT '{}'::jsonb,
    effective_from date NOT NULL DEFAULT CURRENT_DATE,
    effective_to date,
    updated_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CHECK (jsonb_typeof(declarations) = 'object'),
    CHECK (jsonb_typeof(exemptions) = 'object'),
    CHECK (jsonb_typeof(previous_employer_income) = 'object')
);

CREATE TABLE IF NOT EXISTS public.hr_statutory_policy_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    establishment_id bigint NOT NULL REFERENCES public.hr_establishments(id) ON DELETE RESTRICT,
    component text NOT NULL CHECK (component IN ('pf','esi','pt','tds')),
    version_label text NOT NULL,
    effective_from date NOT NULL,
    effective_to date,
    policy_config jsonb NOT NULL,
    source_references jsonb NOT NULL DEFAULT '[]'::jsonb,
    status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','in_review','approved','rejected','superseded')),
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    submitted_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    approved_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    approved_at timestamptz,
    review_due_on date,
    review_note text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CHECK (length(trim(version_label)) > 0),
    CHECK (jsonb_typeof(policy_config) = 'object'),
    CHECK (jsonb_typeof(source_references) = 'array'),
    CHECK ((status = 'approved' AND approved_by_user_id IS NOT NULL AND approved_at IS NOT NULL)
        OR status <> 'approved')
);
CREATE INDEX IF NOT EXISTS hr_statutory_policy_lookup_idx
    ON public.hr_statutory_policy_versions(establishment_id,component,status,effective_from,effective_to);

CREATE TABLE IF NOT EXISTS public.hr_payroll_statutory_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payroll_run_id bigint NOT NULL REFERENCES public.hr_payroll_runs(id) ON DELETE RESTRICT,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    establishment_id bigint NOT NULL REFERENCES public.hr_establishments(id) ON DELETE RESTRICT,
    component text NOT NULL CHECK (component IN ('pf','esi','pt','tds')),
    policy_version_id bigint NOT NULL REFERENCES public.hr_statutory_policy_versions(id) ON DELETE RESTRICT,
    policy_snapshot jsonb NOT NULL,
    input_snapshot jsonb NOT NULL,
    employee_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK (employee_amount >= 0),
    employer_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK (employer_amount >= 0),
    calculation_details jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(payroll_run_id,employee_id,component),
    CHECK (jsonb_typeof(policy_snapshot) = 'object'),
    CHECK (jsonb_typeof(input_snapshot) = 'object'),
    CHECK (jsonb_typeof(calculation_details) = 'object')
);

CREATE TABLE IF NOT EXISTS public.hr_statutory_audit_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    establishment_id bigint REFERENCES public.hr_establishments(id) ON DELETE RESTRICT,
    employee_id bigint REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    policy_version_id bigint REFERENCES public.hr_statutory_policy_versions(id) ON DELETE RESTRICT,
    payroll_run_id bigint REFERENCES public.hr_payroll_runs(id) ON DELETE RESTRICT,
    event_type text NOT NULL,
    reason text NOT NULL,
    before_state jsonb NOT NULL DEFAULT '{}'::jsonb,
    after_state jsonb NOT NULL DEFAULT '{}'::jsonb,
    actor_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(event_type)) > 0),
    CHECK (length(trim(reason)) > 0),
    CHECK (jsonb_typeof(before_state) = 'object'),
    CHECK (jsonb_typeof(after_state) = 'object')
);
CREATE INDEX IF NOT EXISTS hr_statutory_audit_employee_idx
    ON public.hr_statutory_audit_events(employee_id,created_at DESC);
CREATE INDEX IF NOT EXISTS hr_statutory_audit_policy_idx
    ON public.hr_statutory_audit_events(policy_version_id,created_at DESC);




-- Payroll stores employer contributions separately from employee deductions.
ALTER TABLE public.hr_payroll_runs
    ADD COLUMN IF NOT EXISTS total_employer_contributions numeric(16,2) NOT NULL DEFAULT 0;
ALTER TABLE public.hr_payslips
    ADD COLUMN IF NOT EXISTS employer_contributions numeric(14,2) NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS public.hr_statutory_remittances (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payroll_run_id bigint NOT NULL REFERENCES public.hr_payroll_runs(id) ON DELETE RESTRICT,
    establishment_id bigint NOT NULL REFERENCES public.hr_establishments(id) ON DELETE RESTRICT,
    component text NOT NULL CHECK (component IN ('pf','esi','pt','tds')),
    period_start date NOT NULL,
    period_end date NOT NULL,
    due_date date,
    employee_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK (employee_amount >= 0),
    employer_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK (employer_amount >= 0),
    total_amount numeric(14,2) NOT NULL CHECK (total_amount >= 0),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','paid','filed')),
    challan_reference text,
    payment_voucher_id bigint REFERENCES public.accounting_vouchers(id) ON DELETE RESTRICT,
    paid_at timestamptz,
    filed_at timestamptz,
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (period_end >= period_start),
    CHECK (total_amount = employee_amount + employer_amount),
    CHECK ((status = 'pending' AND paid_at IS NULL AND filed_at IS NULL) OR status <> 'pending'),
    CHECK ((status = 'paid' AND paid_at IS NOT NULL AND filed_at IS NULL) OR status <> 'paid'),
    CHECK ((status = 'filed' AND paid_at IS NOT NULL AND filed_at IS NOT NULL AND length(trim(COALESCE(challan_reference,''))) > 0) OR status <> 'filed'),
    UNIQUE(payroll_run_id,establishment_id,component)
);
CREATE INDEX IF NOT EXISTS hr_statutory_remittances_due_idx
    ON public.hr_statutory_remittances(status,due_date,component);

