-- 046: Blanket purchase agreements and controlled release purchase orders.
-- Additive only; release POs continue through the existing PO approval, GRN, QC,
-- inventory and supplier-invoice workflows.

CREATE TABLE IF NOT EXISTS public.purchase_blanket_orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blanket_number varchar(40) NOT NULL UNIQUE,
    supplier_id bigint NOT NULL REFERENCES public.suppliers(id) ON DELETE RESTRICT,
    location_id bigint NOT NULL REFERENCES public.stock_locations(id) ON DELETE RESTRICT,
    title varchar(200) NOT NULL,
    start_date date NOT NULL,
    end_date date NOT NULL,
    currency char(3) NOT NULL DEFAULT 'INR',
    max_contract_value numeric(14,2) CHECK (max_contract_value IS NULL OR max_contract_value > 0),
    status text NOT NULL DEFAULT 'draft'
      CHECK (status IN ('draft','submitted','active','rejected','closed','cancelled','expired')),
    created_by_user_id bigint,
    created_by_email varchar(254) NOT NULL,
    policy_version_id bigint REFERENCES public.organisation_policy_versions(id) ON DELETE RESTRICT,
    approval_revision integer NOT NULL DEFAULT 1 CHECK (approval_revision > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (end_date >= start_date)
);
CREATE TABLE IF NOT EXISTS public.purchase_blanket_order_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blanket_order_id bigint NOT NULL REFERENCES public.purchase_blanket_orders(id) ON DELETE RESTRICT,
    variant_id bigint NOT NULL REFERENCES public.product_variants(id) ON DELETE RESTRICT,
    agreed_quantity numeric(14,3) CHECK (agreed_quantity IS NULL OR agreed_quantity > 0),
    agreed_unit_cost numeric(14,2) NOT NULL CHECK (agreed_unit_cost >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(blanket_order_id, variant_id)
);
CREATE TABLE IF NOT EXISTS public.purchase_blanket_order_releases (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blanket_order_id bigint NOT NULL REFERENCES public.purchase_blanket_orders(id) ON DELETE RESTRICT,
    purchase_order_id bigint NOT NULL UNIQUE REFERENCES public.purchase_orders(id) ON DELETE RESTRICT,
    release_number varchar(40) NOT NULL UNIQUE,
    created_by_user_id bigint,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.purchase_blanket_order_release_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_id bigint NOT NULL REFERENCES public.purchase_blanket_order_releases(id) ON DELETE RESTRICT,
    blanket_line_id bigint NOT NULL REFERENCES public.purchase_blanket_order_lines(id) ON DELETE RESTRICT,
    variant_id bigint NOT NULL REFERENCES public.product_variants(id) ON DELETE RESTRICT,
    quantity numeric(14,3) NOT NULL CHECK (quantity > 0),
    unit_cost numeric(14,2) NOT NULL CHECK (unit_cost >= 0),
    UNIQUE(release_id, blanket_line_id)
);
CREATE INDEX IF NOT EXISTS ix_blanket_orders_supplier_status
    ON public.purchase_blanket_orders(supplier_id,status,end_date);
CREATE INDEX IF NOT EXISTS ix_blanket_releases_agreement
    ON public.purchase_blanket_order_releases(blanket_order_id,created_at);

ALTER TABLE public.purchasing_approval_events
    DROP CONSTRAINT IF EXISTS purchasing_approval_events_document_type_check;
ALTER TABLE public.purchasing_approval_events
    ADD CONSTRAINT purchasing_approval_events_document_type_check
    CHECK (document_type IN ('requisition','purchase_order','quotation','supplier_invoice','supplier_return','blanket_order'));

