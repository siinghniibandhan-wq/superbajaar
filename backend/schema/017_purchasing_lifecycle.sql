-- Purchasing lifecycle foundation: requisition through receipt, QC, invoice,
-- returns and links to posted accounting payments.
-- Additive only. Existing supplier, PO, inventory and accounting ledgers are reused.
-- No inventory balance/movement/cost-layer writes are performed by this migration.

CREATE TABLE IF NOT EXISTS public.purchase_requisitions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requisition_number varchar(40) NOT NULL UNIQUE,
    requester_user_id bigint,
    requester_email varchar(254) NOT NULL,
    department varchar(120),
    cost_centre varchar(120),
    location_id bigint NOT NULL REFERENCES public.stock_locations(id) ON DELETE RESTRICT,
    required_by date,
    justification text NOT NULL CHECK (length(btrim(justification)) >= 3),
    status text NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft','submitted','approved','rejected','cancelled','partially_ordered','ordered')),
    submitted_at timestamptz,
    closed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.purchase_requisition_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requisition_id bigint NOT NULL REFERENCES public.purchase_requisitions(id) ON DELETE RESTRICT,
    variant_id bigint NOT NULL REFERENCES public.product_variants(id) ON DELETE RESTRICT,
    quantity numeric(14,3) NOT NULL CHECK (quantity > 0),
    estimated_unit_cost numeric(14,2) CHECK (estimated_unit_cost IS NULL OR estimated_unit_cost >= 0),
    specification text,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (requisition_id, variant_id)
);

-- Generic immutable decision history. Role/threshold policy is deliberately
-- not hard-coded until the owner approves an approval matrix.
CREATE TABLE IF NOT EXISTS public.purchasing_approval_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_type text NOT NULL CHECK (document_type IN ('requisition','purchase_order','quotation','supplier_invoice','supplier_return')),
    document_id bigint NOT NULL CHECK (document_id > 0),
    action text NOT NULL CHECK (action IN ('submitted','approved','rejected','withdrawn','returned_for_changes')),
    actor_user_id bigint,
    actor_email varchar(254) NOT NULL,
    actor_role varchar(100),
    reason text,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_purchasing_approval_document
    ON public.purchasing_approval_events(document_type, document_id, created_at, id);

CREATE TABLE IF NOT EXISTS public.purchase_rfqs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfq_number varchar(40) NOT NULL UNIQUE,
    requisition_id bigint REFERENCES public.purchase_requisitions(id) ON DELETE RESTRICT,
    status text NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft','issued','evaluation','awarded','cancelled','closed')),
    issue_date date,
    response_due_at timestamptz,
    currency char(3) NOT NULL DEFAULT 'INR',
    terms text,
    created_by_user_id bigint,
    created_by_email varchar(254),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.purchase_rfq_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfq_id bigint NOT NULL REFERENCES public.purchase_rfqs(id) ON DELETE RESTRICT,
    requisition_line_id bigint REFERENCES public.purchase_requisition_lines(id) ON DELETE RESTRICT,
    variant_id bigint NOT NULL REFERENCES public.product_variants(id) ON DELETE RESTRICT,
    quantity numeric(14,3) NOT NULL CHECK (quantity > 0),
    specification text,
    UNIQUE (rfq_id, variant_id)
);

CREATE TABLE IF NOT EXISTS public.purchase_rfq_suppliers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfq_id bigint NOT NULL REFERENCES public.purchase_rfqs(id) ON DELETE RESTRICT,
    supplier_id bigint NOT NULL REFERENCES public.suppliers(id) ON DELETE RESTRICT,
    invited_at timestamptz NOT NULL DEFAULT now(),
    response_status text NOT NULL DEFAULT 'invited'
        CHECK (response_status IN ('invited','responded','declined','no_response')),
    UNIQUE (rfq_id, supplier_id)
);

CREATE TABLE IF NOT EXISTS public.supplier_quotations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_number varchar(80) NOT NULL,
    rfq_id bigint REFERENCES public.purchase_rfqs(id) ON DELETE RESTRICT,
    supplier_id bigint NOT NULL REFERENCES public.suppliers(id) ON DELETE RESTRICT,
    status text NOT NULL DEFAULT 'received'
        CHECK (status IN ('received','under_review','selected','rejected','expired','withdrawn')),
    quoted_at timestamptz NOT NULL DEFAULT now(),
    valid_until date,
    lead_time_days integer CHECK (lead_time_days IS NULL OR lead_time_days >= 0),
    currency char(3) NOT NULL DEFAULT 'INR',
    freight_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK (freight_amount >= 0),
    discount_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    tax_amount numeric(14,2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
    payment_terms text,
    delivery_terms text,
    evaluation_notes text,
    created_by_user_id bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (supplier_id, quotation_number)
);

CREATE TABLE IF NOT EXISTS public.supplier_quotation_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id bigint NOT NULL REFERENCES public.supplier_quotations(id) ON DELETE RESTRICT,
    rfq_line_id bigint REFERENCES public.purchase_rfq_lines(id) ON DELETE RESTRICT,
    variant_id bigint NOT NULL REFERENCES public.product_variants(id) ON DELETE RESTRICT,
    quantity numeric(14,3) NOT NULL CHECK (quantity > 0),
    unit_price numeric(14,2) NOT NULL CHECK (unit_price >= 0),
    hsn_sac varchar(8),
    gst_rate numeric(5,2) CHECK (gst_rate IS NULL OR (gst_rate >= 0 AND gst_rate <= 100)),
    UNIQUE (quotation_id, variant_id)
);

CREATE TABLE IF NOT EXISTS public.purchase_order_provenance (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id bigint NOT NULL UNIQUE REFERENCES public.purchase_orders(id) ON DELETE RESTRICT,
    requisition_id bigint REFERENCES public.purchase_requisitions(id) ON DELETE RESTRICT,
    awarded_quotation_id bigint REFERENCES public.supplier_quotations(id) ON DELETE RESTRICT,
    created_by_user_id bigint,
    created_by_email varchar(254),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.purchase_order_amendments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id bigint NOT NULL REFERENCES public.purchase_orders(id) ON DELETE RESTRICT,
    version_number integer NOT NULL CHECK (version_number > 0),
    before_document jsonb NOT NULL,
    after_document jsonb NOT NULL,
    reason text NOT NULL CHECK (length(btrim(reason)) >= 3),
    changed_by_user_id bigint,
    changed_by_email varchar(254) NOT NULL,
    approved_by_user_id bigint,
    approved_by_email varchar(254),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (purchase_order_id, version_number)
);

CREATE TABLE IF NOT EXISTS public.supplier_dispatch_notices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id bigint NOT NULL REFERENCES public.purchase_orders(id) ON DELETE RESTRICT,
    supplier_id bigint NOT NULL REFERENCES public.suppliers(id) ON DELETE RESTRICT,
    supplier_dispatch_reference varchar(100),
    dispatched_at timestamptz,
    expected_arrival_at timestamptz,
    carrier_name varchar(160),
    tracking_reference varchar(160),
    evidence_uri text,
    notes text,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_supplier_dispatch_po
    ON public.supplier_dispatch_notices(purchase_order_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.goods_receipts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grn_number varchar(40) NOT NULL UNIQUE,
    purchase_order_id bigint NOT NULL REFERENCES public.purchase_orders(id) ON DELETE RESTRICT,
    supplier_id bigint NOT NULL REFERENCES public.suppliers(id) ON DELETE RESTRICT,
    location_id bigint NOT NULL REFERENCES public.stock_locations(id) ON DELETE RESTRICT,
    idempotency_key uuid NOT NULL,
    payload_hash char(64) NOT NULL CHECK (payload_hash ~ '^[0-9a-f]{64}$'),
    supplier_delivery_note varchar(120),
    received_by_user_id bigint,
    received_by_email varchar(254),
    received_at timestamptz NOT NULL DEFAULT now(),
    note text,
    status text NOT NULL DEFAULT 'received'
        CHECK (status IN ('received','qc_pending','partially_accepted','accepted','rejected','cancelled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (purchase_order_id, idempotency_key)
);
CREATE INDEX IF NOT EXISTS ix_goods_receipts_po_time
    ON public.goods_receipts(purchase_order_id, received_at DESC);

CREATE TABLE IF NOT EXISTS public.goods_receipt_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goods_receipt_id bigint NOT NULL REFERENCES public.goods_receipts(id) ON DELETE RESTRICT,
    purchase_order_line_id bigint NOT NULL REFERENCES public.purchase_order_lines(id) ON DELETE RESTRICT,
    variant_id bigint NOT NULL REFERENCES public.product_variants(id) ON DELETE RESTRICT,
    received_quantity numeric(14,3) NOT NULL CHECK (received_quantity > 0),
    accepted_quantity numeric(14,3) NOT NULL DEFAULT 0 CHECK (accepted_quantity >= 0),
    rejected_quantity numeric(14,3) NOT NULL DEFAULT 0 CHECK (rejected_quantity >= 0),
    damaged_quantity numeric(14,3) NOT NULL DEFAULT 0 CHECK (damaged_quantity >= 0),
    quarantined_quantity numeric(14,3) NOT NULL DEFAULT 0 CHECK (quarantined_quantity >= 0),
    batch_code varchar(120),
    manufacture_date date,
    expiry_date date,
    unit_cost numeric(14,2) NOT NULL CHECK (unit_cost >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (accepted_quantity + rejected_quantity + damaged_quantity + quarantined_quantity <= received_quantity),
    CHECK (expiry_date IS NULL OR manufacture_date IS NULL OR expiry_date >= manufacture_date),
    UNIQUE (goods_receipt_id, purchase_order_line_id)
);
CREATE INDEX IF NOT EXISTS ix_goods_receipt_lines_po_line
    ON public.goods_receipt_lines(purchase_order_line_id);

CREATE TABLE IF NOT EXISTS public.goods_receipt_qc_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goods_receipt_line_id bigint NOT NULL REFERENCES public.goods_receipt_lines(id) ON DELETE RESTRICT,
    disposition text NOT NULL CHECK (disposition IN ('accepted','rejected','damaged','quarantined','released')),
    quantity numeric(14,3) NOT NULL CHECK (quantity > 0),
    reason text,
    actor_user_id bigint,
    actor_email varchar(254) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_grn_qc_line_time
    ON public.goods_receipt_qc_events(goods_receipt_line_id, created_at, id);

CREATE TABLE IF NOT EXISTS public.supplier_invoices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id bigint NOT NULL REFERENCES public.suppliers(id) ON DELETE RESTRICT,
    purchase_order_id bigint NOT NULL REFERENCES public.purchase_orders(id) ON DELETE RESTRICT,
    supplier_gstin char(15),
    invoice_number varchar(100) NOT NULL,
    invoice_date date NOT NULL,
    due_date date,
    currency char(3) NOT NULL DEFAULT 'INR',
    taxable_value numeric(16,2) NOT NULL CHECK (taxable_value >= 0),
    cgst_amount numeric(16,2) NOT NULL DEFAULT 0 CHECK (cgst_amount >= 0),
    sgst_amount numeric(16,2) NOT NULL DEFAULT 0 CHECK (sgst_amount >= 0),
    igst_amount numeric(16,2) NOT NULL DEFAULT 0 CHECK (igst_amount >= 0),
    cess_amount numeric(16,2) NOT NULL DEFAULT 0 CHECK (cess_amount >= 0),
    freight_amount numeric(16,2) NOT NULL DEFAULT 0 CHECK (freight_amount >= 0),
    discount_amount numeric(16,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    invoice_total numeric(16,2) NOT NULL CHECK (invoice_total > 0),
    source_document_uri text,
    match_status text NOT NULL DEFAULT 'pending'
        CHECK (match_status IN ('pending','matched','variance','blocked','approved','rejected')),
    accounting_voucher_id bigint REFERENCES public.accounting_vouchers(id) ON DELETE RESTRICT,
    created_by_user_id bigint,
    created_by_email varchar(254),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (supplier_id, invoice_number),
    CHECK (due_date IS NULL OR due_date >= invoice_date)
);
CREATE INDEX IF NOT EXISTS ix_supplier_invoices_po
    ON public.supplier_invoices(purchase_order_id, invoice_date DESC);

CREATE TABLE IF NOT EXISTS public.supplier_invoice_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_invoice_id bigint NOT NULL REFERENCES public.supplier_invoices(id) ON DELETE RESTRICT,
    purchase_order_line_id bigint NOT NULL REFERENCES public.purchase_order_lines(id) ON DELETE RESTRICT,
    goods_receipt_line_id bigint REFERENCES public.goods_receipt_lines(id) ON DELETE RESTRICT,
    variant_id bigint NOT NULL REFERENCES public.product_variants(id) ON DELETE RESTRICT,
    quantity numeric(14,3) NOT NULL CHECK (quantity > 0),
    unit_rate numeric(14,2) NOT NULL CHECK (unit_rate >= 0),
    taxable_value numeric(16,2) NOT NULL CHECK (taxable_value >= 0),
    hsn_sac varchar(8),
    gst_rate numeric(5,2) CHECK (gst_rate IS NULL OR (gst_rate >= 0 AND gst_rate <= 100)),
    cgst_amount numeric(16,2) NOT NULL DEFAULT 0 CHECK (cgst_amount >= 0),
    sgst_amount numeric(16,2) NOT NULL DEFAULT 0 CHECK (sgst_amount >= 0),
    igst_amount numeric(16,2) NOT NULL DEFAULT 0 CHECK (igst_amount >= 0)
);

CREATE TABLE IF NOT EXISTS public.supplier_returns (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_number varchar(40) NOT NULL UNIQUE,
    supplier_id bigint NOT NULL REFERENCES public.suppliers(id) ON DELETE RESTRICT,
    purchase_order_id bigint NOT NULL REFERENCES public.purchase_orders(id) ON DELETE RESTRICT,
    goods_receipt_id bigint REFERENCES public.goods_receipts(id) ON DELETE RESTRICT,
    supplier_invoice_id bigint REFERENCES public.supplier_invoices(id) ON DELETE RESTRICT,
    status text NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft','submitted','approved','dispatched','credited','cancelled')),
    reason text NOT NULL CHECK (length(btrim(reason)) >= 3),
    debit_note_number varchar(100),
    debit_note_date date,
    accounting_voucher_id bigint REFERENCES public.accounting_vouchers(id) ON DELETE RESTRICT,
    created_by_user_id bigint,
    created_by_email varchar(254),
    approved_by_user_id bigint,
    approved_by_email varchar(254),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.supplier_return_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_return_id bigint NOT NULL REFERENCES public.supplier_returns(id) ON DELETE RESTRICT,
    goods_receipt_line_id bigint NOT NULL REFERENCES public.goods_receipt_lines(id) ON DELETE RESTRICT,
    variant_id bigint NOT NULL REFERENCES public.product_variants(id) ON DELETE RESTRICT,
    quantity numeric(14,3) NOT NULL CHECK (quantity > 0),
    unit_cost numeric(14,2) NOT NULL CHECK (unit_cost >= 0),
    reason text,
    UNIQUE (supplier_return_id, goods_receipt_line_id)
);

-- This table is only a reconciliation link to an already-posted Accounting
-- payment voucher; it does not create or assert bank settlement.
CREATE TABLE IF NOT EXISTS public.supplier_payment_allocations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_invoice_id bigint NOT NULL REFERENCES public.supplier_invoices(id) ON DELETE RESTRICT,
    accounting_voucher_id bigint NOT NULL REFERENCES public.accounting_vouchers(id) ON DELETE RESTRICT,
    allocated_amount numeric(16,2) NOT NULL CHECK (allocated_amount > 0),
    currency char(3) NOT NULL DEFAULT 'INR',
    allocated_at timestamptz NOT NULL DEFAULT now(),
    created_by_user_id bigint,
    created_by_email varchar(254),
    UNIQUE (supplier_invoice_id, accounting_voucher_id)
);

