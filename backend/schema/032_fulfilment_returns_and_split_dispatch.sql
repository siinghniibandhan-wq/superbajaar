-- 032: controlled fulfilment returns and package-to-dispatch provenance.
-- Additive and idempotent. Historical numbered migrations remain untouched.

ALTER TABLE public.stock_locations
    ADD COLUMN IF NOT EXISTS is_fulfillable boolean NOT NULL DEFAULT true;

ALTER TABLE public.fulfilment_return_lines
    ADD COLUMN IF NOT EXISTS disposition_location_id bigint
        REFERENCES public.stock_locations(id) ON DELETE RESTRICT,
    ADD COLUMN IF NOT EXISTS accounting_voucher_id bigint
        REFERENCES public.accounting_vouchers(id) ON DELETE RESTRICT,
    ADD COLUMN IF NOT EXISTS disposition_posted_at timestamptz;

ALTER TABLE public.fulfilment_dispatch_event_lines
    ADD COLUMN IF NOT EXISTS package_line_id bigint
        REFERENCES public.fulfilment_package_lines(id) ON DELETE RESTRICT;

ALTER TABLE public.fulfilment_dispatch_event_lines
    DROP CONSTRAINT IF EXISTS fulfilment_dispatch_event_lines_dispatch_event_id_inventory_movement_id_key;
CREATE UNIQUE INDEX IF NOT EXISTS fulfilment_dispatch_event_lines_unpacked_once_idx
    ON public.fulfilment_dispatch_event_lines(dispatch_event_id,inventory_movement_id)
    WHERE package_line_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS fulfilment_dispatch_event_lines_package_once_idx
    ON public.fulfilment_dispatch_event_lines(dispatch_event_id,inventory_movement_id,package_line_id)
    WHERE package_line_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.fulfilment_return_dispatch_allocations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_line_id bigint NOT NULL
        REFERENCES public.fulfilment_return_lines(id) ON DELETE RESTRICT,
    source_dispatch_movement_id bigint NOT NULL
        REFERENCES public.inventory_movements(id) ON DELETE RESTRICT,
    source_cost_layer_id bigint NOT NULL
        REFERENCES public.inventory_cost_layers(id) ON DELETE RESTRICT,
    quantity numeric(14,3) NOT NULL CHECK (quantity > 0),
    unit_cost numeric(14,4) NOT NULL CHECK (unit_cost >= 0),
    total_cost numeric(16,2) NOT NULL
        CHECK (total_cost >= 0 AND total_cost = round(quantity * unit_cost, 2)),
    disposition text NOT NULL
        CHECK (disposition IN ('restock','quarantine','repair','write_off')),
    destination_location_id bigint
        REFERENCES public.stock_locations(id) ON DELETE RESTRICT,
    inventory_movement_id bigint
        REFERENCES public.inventory_movements(id) ON DELETE RESTRICT,
    accounting_voucher_id bigint
        REFERENCES public.accounting_vouchers(id) ON DELETE RESTRICT,
    posted_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (return_line_id, source_dispatch_movement_id, source_cost_layer_id),
    CHECK (disposition='write_off' OR (destination_location_id IS NOT NULL AND inventory_movement_id IS NOT NULL))
);

