-- Seed maker-checker drafts. Finance must review and approve each mapping
-- through Accounting before any production return posting can use it.
WITH legal_entities AS (
    SELECT code AS legal_entity_code FROM public.hr_establishments
    UNION SELECT 'DEFAULT'
), required_roles AS (
    SELECT * FROM (VALUES
        ('inventory_return','inventory_asset','1200','Restore returned stock at original dispatch cost'),
        ('inventory_return','inventory_cogs_reversal','5000','Reverse cost of goods sold for physically returned stock'),
        ('inventory_return_writeoff','inventory_return_writeoff_expense','5020','Recognise non-recoverable returned stock write-off'),
        ('inventory_return_writeoff','inventory_cogs_reversal','5000','Reverse original COGS for written-off returned stock')
    ) AS v(event_type,line_role,account_code,notes)
)
INSERT INTO public.accounting_event_account_mappings
    (legal_entity_code,source_module,event_type,line_role,account_id,effective_from,status,source_reference,notes)
SELECT le.legal_entity_code,'inventory',rr.event_type,rr.line_role,a.id,CURRENT_DATE,'draft',
       'fulfilment-return-accounting-v1',rr.notes
FROM legal_entities le
CROSS JOIN required_roles rr
JOIN public.accounting_accounts a ON a.code=rr.account_code AND a.is_active
WHERE NOT EXISTS (
    SELECT 1 FROM public.accounting_event_account_mappings m
    WHERE m.legal_entity_code=le.legal_entity_code AND m.source_module='inventory'
      AND m.event_type=rr.event_type AND m.line_role=rr.line_role
      AND m.tax_component IS NULL AND m.effective_from=CURRENT_DATE
      AND m.source_reference='fulfilment-return-accounting-v1'
);

