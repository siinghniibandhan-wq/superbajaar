-- Catalogue product configuration: presentation, sales channels, delivery and geographic restrictions.
-- Safe to re-run; existing products retain compatible defaults.
ALTER TABLE public.product_attributes
    ADD COLUMN IF NOT EXISTS display_style text NOT NULL DEFAULT 'text';

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.product_attributes'::regclass
          AND conname = 'product_attributes_display_style_check'
    ) THEN
        ALTER TABLE public.product_attributes
            ADD CONSTRAINT product_attributes_display_style_check
            CHECK (display_style IN ('text', 'button', 'colour_swatch', 'dropdown'));
    END IF;
END $$;

ALTER TABLE public.products
    ADD COLUMN IF NOT EXISTS pos_enabled boolean NOT NULL DEFAULT true,
    ADD COLUMN IF NOT EXISTS website_enabled boolean NOT NULL DEFAULT true,
    ADD COLUMN IF NOT EXISTS standard_delivery_enabled boolean NOT NULL DEFAULT true,
    ADD COLUMN IF NOT EXISTS express_delivery_enabled boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.product_availability_restrictions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    restriction_type text NOT NULL,
    restriction_value text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT product_availability_restrictions_type_check
        CHECK (restriction_type IN ('region', 'state', 'warehouse', 'pincode')),
    CONSTRAINT product_availability_restrictions_value_check
        CHECK (length(trim(restriction_value)) > 0),
    CONSTRAINT product_availability_restrictions_unique
        UNIQUE (product_id, restriction_type, restriction_value)
);

CREATE INDEX IF NOT EXISTS product_availability_restrictions_product_idx
    ON public.product_availability_restrictions(product_id);


-- Central GST rate master used by the product tax selector.
CREATE TABLE IF NOT EXISTS public.tax_rates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    label text NOT NULL,
    rate numeric(5,2) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT tax_rates_rate_check CHECK (rate >= 0 AND rate <= 100),
    CONSTRAINT tax_rates_label_check CHECK (length(trim(label)) > 0)
);

