-- 043: Additive foundation for the Super Bajaar unified identity system.
-- Existing customer, employee, supplier, login, loyalty and referral rows are not rewritten.
-- This migration is schema-only; no backfill, account linking or production operation is performed.

CREATE TABLE IF NOT EXISTS public.identity_parties (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sbid text NOT NULL UNIQUE
        DEFAULT ('SBID-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 20))),
    party_type text NOT NULL CHECK (party_type IN ('individual','organisation')),
    display_name text NOT NULL,
    status text NOT NULL DEFAULT 'active'
        CHECK (status IN ('active','inactive','merged','under_review')),
    merged_into_party_id bigint REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(display_name)) > 0),
    CHECK ((status = 'merged' AND merged_into_party_id IS NOT NULL)
        OR (status <> 'merged' AND merged_into_party_id IS NULL)),
    CHECK (merged_into_party_id IS NULL OR merged_into_party_id <> id)
);
CREATE INDEX IF NOT EXISTS identity_parties_status_type_idx
    ON public.identity_parties(status,party_type,created_at DESC);
CREATE INDEX IF NOT EXISTS identity_parties_merged_into_idx
    ON public.identity_parties(merged_into_party_id)
    WHERE merged_into_party_id IS NOT NULL;

CREATE OR REPLACE FUNCTION public.identity_party_core_immutable()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.sbid IS DISTINCT FROM OLD.sbid THEN
        RAISE EXCEPTION 'SBID is permanent and cannot be changed';
    END IF;
    IF NEW.party_type IS DISTINCT FROM OLD.party_type THEN
        RAISE EXCEPTION 'Identity party type cannot be changed';
    END IF;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS identity_party_core_immutable_trigger ON public.identity_parties;
CREATE TRIGGER identity_party_core_immutable_trigger
    BEFORE UPDATE ON public.identity_parties
    FOR EACH ROW EXECUTE FUNCTION public.identity_party_core_immutable();

CREATE TABLE IF NOT EXISTS public.identity_profiles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id bigint NOT NULL REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    profile_type text NOT NULL
        CHECK (profile_type IN ('customer_account','crm_customer','employee','vendor_organisation')),
    customer_account_id bigint REFERENCES public.customer_accounts(id) ON DELETE RESTRICT,
    crm_customer_id bigint REFERENCES public.customers(id) ON DELETE RESTRICT,
    employee_id bigint REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    supplier_id bigint REFERENCES public.suppliers(id) ON DELETE RESTRICT,
    status text NOT NULL DEFAULT 'active'
        CHECK (status IN ('active','inactive','suspended')),
    valid_from timestamptz NOT NULL DEFAULT now(),
    valid_to timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (valid_to IS NULL OR valid_to >= valid_from),
    CHECK (
        (profile_type = 'customer_account' AND customer_account_id IS NOT NULL
            AND crm_customer_id IS NULL AND employee_id IS NULL AND supplier_id IS NULL)
        OR (profile_type = 'crm_customer' AND customer_account_id IS NULL
            AND crm_customer_id IS NOT NULL AND employee_id IS NULL AND supplier_id IS NULL)
        OR (profile_type = 'employee' AND customer_account_id IS NULL
            AND crm_customer_id IS NULL AND employee_id IS NOT NULL AND supplier_id IS NULL)
        OR (profile_type = 'vendor_organisation' AND customer_account_id IS NULL
            AND crm_customer_id IS NULL AND employee_id IS NULL AND supplier_id IS NOT NULL)
    )
);
CREATE OR REPLACE FUNCTION public.identity_profile_party_type_guard()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_party_type text;
BEGIN
    SELECT party_type INTO v_party_type
    FROM public.identity_parties
    WHERE id = NEW.party_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Identity party does not exist';
    END IF;
    IF (NEW.profile_type = 'vendor_organisation' AND v_party_type <> 'organisation')
       OR (NEW.profile_type <> 'vendor_organisation' AND v_party_type <> 'individual') THEN
        RAISE EXCEPTION 'Profile type % is incompatible with party type %', NEW.profile_type, v_party_type;
    END IF;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS identity_profile_party_type_guard_trigger ON public.identity_profiles;
CREATE TRIGGER identity_profile_party_type_guard_trigger
    BEFORE INSERT OR UPDATE OF party_id,profile_type ON public.identity_profiles
    FOR EACH ROW EXECUTE FUNCTION public.identity_profile_party_type_guard();

CREATE UNIQUE INDEX IF NOT EXISTS identity_profile_customer_uidx
    ON public.identity_profiles(customer_account_id) WHERE customer_account_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS identity_profile_crm_customer_uidx
    ON public.identity_profiles(crm_customer_id) WHERE crm_customer_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS identity_profile_employee_uidx
    ON public.identity_profiles(employee_id) WHERE employee_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS identity_profile_supplier_uidx
    ON public.identity_profiles(supplier_id) WHERE supplier_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS identity_profiles_party_type_status_idx
    ON public.identity_profiles(party_id,profile_type,status);

CREATE TABLE IF NOT EXISTS public.identity_auth_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id bigint NOT NULL REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    account_type text NOT NULL CHECK (account_type IN ('customer','staff')),
    customer_account_id bigint REFERENCES public.customer_accounts(id) ON DELETE RESTRICT,
    app_user_id bigint REFERENCES public.app_users(id) ON DELETE RESTRICT,
    link_method text NOT NULL
        CHECK (link_method IN ('authenticated_claim','verified_invitation','admin_verified','migration')),
    status text NOT NULL DEFAULT 'active'
        CHECK (status IN ('active','inactive','revoked')),
    linked_at timestamptz NOT NULL DEFAULT now(),
    linked_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (
        (account_type = 'customer' AND customer_account_id IS NOT NULL AND app_user_id IS NULL)
        OR (account_type = 'staff' AND customer_account_id IS NULL AND app_user_id IS NOT NULL)
    )
);
CREATE OR REPLACE FUNCTION public.identity_auth_party_type_guard()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_party_type text;
BEGIN
    SELECT party_type INTO v_party_type
    FROM public.identity_parties
    WHERE id = NEW.party_id;
    IF v_party_type IS DISTINCT FROM 'individual' THEN
        RAISE EXCEPTION 'Authentication accounts must link to an individual identity';
    END IF;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS identity_auth_party_type_guard_trigger ON public.identity_auth_accounts;
CREATE TRIGGER identity_auth_party_type_guard_trigger
    BEFORE INSERT OR UPDATE OF party_id,account_type ON public.identity_auth_accounts
    FOR EACH ROW EXECUTE FUNCTION public.identity_auth_party_type_guard();

CREATE UNIQUE INDEX IF NOT EXISTS identity_auth_customer_account_uidx
    ON public.identity_auth_accounts(customer_account_id) WHERE customer_account_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS identity_auth_app_user_uidx
    ON public.identity_auth_accounts(app_user_id) WHERE app_user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS identity_auth_party_status_idx
    ON public.identity_auth_accounts(party_id,status);

CREATE TABLE IF NOT EXISTS public.identity_contacts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id bigint NOT NULL REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    contact_type text NOT NULL CHECK (contact_type IN ('email','phone')),
    normalized_value text NOT NULL,
    display_value text NOT NULL,
    verification_status text NOT NULL DEFAULT 'unverified'
        CHECK (verification_status IN ('unverified','verified','expired','revoked')),
    verified_at timestamptz,
    valid_from timestamptz NOT NULL DEFAULT now(),
    valid_to timestamptz,
    is_primary boolean NOT NULL DEFAULT false,
    source text NOT NULL DEFAULT 'self_service',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(normalized_value)) > 0),
    CHECK (length(trim(display_value)) > 0),
    CHECK (valid_to IS NULL OR valid_to >= valid_from),
    CHECK ((verification_status = 'verified' AND verified_at IS NOT NULL)
        OR verification_status <> 'verified')
);
CREATE UNIQUE INDEX IF NOT EXISTS identity_contact_party_value_uidx
    ON public.identity_contacts(party_id,contact_type,normalized_value)
    WHERE valid_to IS NULL AND verification_status <> 'revoked';
CREATE UNIQUE INDEX IF NOT EXISTS identity_contact_primary_uidx
    ON public.identity_contacts(party_id,contact_type)
    WHERE is_primary = true AND valid_to IS NULL AND verification_status = 'verified';
CREATE INDEX IF NOT EXISTS identity_contacts_normalized_lookup_idx
    ON public.identity_contacts(contact_type,normalized_value,verification_status);
CREATE INDEX IF NOT EXISTS identity_contacts_party_idx
    ON public.identity_contacts(party_id,contact_type,created_at DESC);

CREATE TABLE IF NOT EXISTS public.identity_relationships (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_party_id bigint NOT NULL REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    to_party_id bigint NOT NULL REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    relationship_type text NOT NULL
        CHECK (relationship_type IN ('representative','owner','director','employee','authorised_vendor_user','accountant','business_partner','other')),
    scope jsonb NOT NULL DEFAULT '{}'::jsonb,
    status text NOT NULL DEFAULT 'active'
        CHECK (status IN ('pending','active','suspended','revoked','expired')),
    valid_from timestamptz NOT NULL DEFAULT now(),
    valid_to timestamptz,
    reason text,
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    approved_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (from_party_id <> to_party_id),
    CHECK (jsonb_typeof(scope) = 'object'),
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);
CREATE UNIQUE INDEX IF NOT EXISTS identity_relationship_active_uidx
    ON public.identity_relationships(from_party_id,to_party_id,relationship_type)
    WHERE status IN ('pending','active');
CREATE INDEX IF NOT EXISTS identity_relationship_to_party_idx
    ON public.identity_relationships(to_party_id,status,relationship_type);
CREATE INDEX IF NOT EXISTS identity_relationship_from_party_idx
    ON public.identity_relationships(from_party_id,status,relationship_type);

CREATE TABLE IF NOT EXISTS public.identity_link_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key text NOT NULL,
    requester_party_id bigint REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    target_party_id bigint REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    request_type text NOT NULL
        CHECK (request_type IN ('claim_existing_identity','link_profile','link_auth_account','link_contact','merge_parties','organisation_relationship')),
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','proof_required','approved','rejected','expired','cancelled')),
    proof_method text,
    proof_verified_at timestamptz,
    requested_profile_type text,
    requested_source_id text,
    reviewer_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    review_reason text,
    expires_at timestamptz NOT NULL,
    reviewed_at timestamptz,
    request_context jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(idempotency_key)) >= 8),
    CHECK (jsonb_typeof(request_context) = 'object'),
    CHECK (reviewed_at IS NULL OR status IN ('approved','rejected','cancelled','expired'))
);
CREATE UNIQUE INDEX IF NOT EXISTS identity_link_requests_idempotency_uidx
    ON public.identity_link_requests(idempotency_key);
CREATE INDEX IF NOT EXISTS identity_link_requests_queue_idx
    ON public.identity_link_requests(status,created_at DESC);
CREATE INDEX IF NOT EXISTS identity_link_requests_parties_idx
    ON public.identity_link_requests(requester_party_id,target_party_id,created_at DESC);

CREATE TABLE IF NOT EXISTS public.identity_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id bigint REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    event_type text NOT NULL
        CHECK (event_type IN ('party_created','party_updated','profile_linked','profile_unlinked',
            'auth_account_linked','auth_account_unlinked','contact_added','contact_verified',
            'contact_revoked','relationship_created','relationship_approved','relationship_revoked',
            'link_requested','link_approved','link_rejected','party_merged','party_split',
            'party_deactivated','party_reactivated')),
    actor_party_id bigint REFERENCES public.identity_parties(id) ON DELETE SET NULL,
    actor_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    actor_email text,
    actor_role text,
    reason text,
    request_id text,
    event_data jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (jsonb_typeof(event_data) = 'object')
);
CREATE INDEX IF NOT EXISTS identity_events_party_created_idx
    ON public.identity_events(party_id,created_at DESC,id DESC);
CREATE INDEX IF NOT EXISTS identity_events_request_idx
    ON public.identity_events(request_id) WHERE request_id IS NOT NULL;

CREATE OR REPLACE FUNCTION public.identity_events_immutable()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Identity audit events are immutable';
END $$;
DROP TRIGGER IF EXISTS identity_events_immutable_trigger ON public.identity_events;
CREATE TRIGGER identity_events_immutable_trigger
    BEFORE UPDATE OR DELETE ON public.identity_events
    FOR EACH ROW EXECUTE FUNCTION public.identity_events_immutable();

CREATE TABLE IF NOT EXISTS public.identity_aliases (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias_sbid text NOT NULL UNIQUE,
    source_party_id bigint NOT NULL REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    canonical_party_id bigint NOT NULL REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    merge_reason text NOT NULL,
    merged_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (source_party_id <> canonical_party_id),
    CHECK (length(trim(alias_sbid)) > 0),
    CHECK (length(trim(merge_reason)) >= 5)
);
CREATE INDEX IF NOT EXISTS identity_aliases_canonical_idx
    ON public.identity_aliases(canonical_party_id);

