-- 076: employee loan ledger and effective-dated exit settlement policy.
CREATE TABLE IF NOT EXISTS public.hr_employee_loans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    loan_reference text NOT NULL UNIQUE,
    principal_amount numeric(14,2) NOT NULL CHECK (principal_amount > 0),
    outstanding_amount numeric(14,2) NOT NULL CHECK (outstanding_amount >= 0 AND outstanding_amount <= principal_amount),
    currency char(3) NOT NULL DEFAULT 'INR',
    status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','approved','active','closed','cancelled')),
    approved_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    approved_at timestamptz,
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((status IN ('approved','active','closed') AND approved_by_user_id IS NOT NULL AND approved_at IS NOT NULL) OR status NOT IN ('approved','active','closed'))
);
CREATE TABLE IF NOT EXISTS public.hr_employee_loan_transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id bigint NOT NULL REFERENCES public.hr_employee_loans(id) ON DELETE RESTRICT,
    transaction_type text NOT NULL CHECK (transaction_type IN ('disbursement','repayment','settlement_recovery','adjustment','reversal')),
    amount numeric(14,2) NOT NULL CHECK (amount > 0),
    transaction_date date NOT NULL,
    reference text,
    payroll_adjustment_id bigint REFERENCES public.hr_payroll_earning_adjustments(id) ON DELETE RESTRICT,
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS hr_employee_loans_employee_status_idx ON public.hr_employee_loans(employee_id,status);
CREATE INDEX IF NOT EXISTS hr_employee_loan_transactions_loan_date_idx ON public.hr_employee_loan_transactions(loan_id,transaction_date,id);

CREATE TABLE IF NOT EXISTS public.hr_exit_statutory_policy_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    establishment_id bigint NOT NULL REFERENCES public.hr_establishments(id) ON DELETE RESTRICT,
    version_label text NOT NULL,
    jurisdiction_code text NOT NULL,
    effective_from date NOT NULL,
    effective_to date,
    policy_config jsonb NOT NULL,
    source_references jsonb NOT NULL DEFAULT '[]'::jsonb,
    status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','in_review','approved','rejected','superseded')),
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    approved_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    approved_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CHECK (jsonb_typeof(policy_config)='object'),
    CHECK (jsonb_typeof(source_references)='array'),
    CHECK ((status='approved' AND approved_by_user_id IS NOT NULL AND approved_at IS NOT NULL) OR status<>'approved')
);
CREATE INDEX IF NOT EXISTS hr_exit_statutory_policy_lookup_idx
    ON public.hr_exit_statutory_policy_versions(establishment_id,status,effective_from,effective_to);
