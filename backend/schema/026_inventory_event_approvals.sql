-- Inventory maker-checker requests. Additive and safe to apply repeatedly.
CREATE TABLE IF NOT EXISTS public.inventory_event_approval_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    establishment_id bigint NOT NULL REFERENCES public.hr_establishments(id) ON DELETE RESTRICT,
    policy_version_id bigint NOT NULL REFERENCES public.organisation_policy_versions(id) ON DELETE RESTRICT,
    event_type text NOT NULL,
    location_id bigint NOT NULL REFERENCES public.stock_locations(id) ON DELETE RESTRICT,
    payload jsonb NOT NULL,
    payload_hash char(64) NOT NULL,
    created_by_user_id bigint NOT NULL REFERENCES public.app_users(id) ON DELETE RESTRICT,
    created_by_email varchar(254) NOT NULL,
    created_by_role varchar(100) NOT NULL,
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','approved','rejected','posted')),
    posted_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (jsonb_typeof(payload) = 'object'),
    CHECK (length(trim(event_type)) > 0),
    CHECK ((status = 'posted' AND posted_at IS NOT NULL) OR status <> 'posted')
);
CREATE INDEX IF NOT EXISTS ix_inventory_event_approval_queue
    ON public.inventory_event_approval_requests(establishment_id,status,created_at DESC);
CREATE INDEX IF NOT EXISTS ix_inventory_event_approval_hash
    ON public.inventory_event_approval_requests(payload_hash,status);

