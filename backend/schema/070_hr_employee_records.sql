-- 070: employee emergency contacts and append-only prior employment history.
-- HR manager access is enforced by the API; history and audit events are immutable.

CREATE TABLE IF NOT EXISTS public.hr_employee_emergency_contacts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    contact_name varchar(160) NOT NULL,
    relationship varchar(80) NOT NULL,
    phone varchar(32) NOT NULL,
    alternate_phone varchar(32),
    email varchar(254),
    address text,
    is_primary boolean NOT NULL DEFAULT false,
    is_active boolean NOT NULL DEFAULT true,
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    updated_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(contact_name)) > 0),
    CHECK (length(trim(relationship)) > 0),
    CHECK (length(trim(phone)) > 0)
);
CREATE INDEX IF NOT EXISTS hr_employee_emergency_contacts_employee_idx
    ON public.hr_employee_emergency_contacts(employee_id,is_active,created_at);
CREATE UNIQUE INDEX IF NOT EXISTS hr_employee_emergency_contacts_primary_idx
    ON public.hr_employee_emergency_contacts(employee_id)
    WHERE is_active=true AND is_primary=true;

CREATE TABLE IF NOT EXISTS public.hr_employee_employment_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    employer_name varchar(180) NOT NULL,
    job_title varchar(160) NOT NULL,
    employment_type varchar(24) NOT NULL DEFAULT 'full_time'
        CHECK (employment_type IN ('full_time','part_time','contract','intern','self_employed','other')),
    location varchar(180),
    start_date date NOT NULL,
    end_date date,
    description text,
    recorded_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(employer_name)) > 0),
    CHECK (length(trim(job_title)) > 0),
    CHECK (end_date IS NULL OR end_date >= start_date)
);
CREATE INDEX IF NOT EXISTS hr_employee_employment_history_employee_idx
    ON public.hr_employee_employment_history(employee_id,start_date DESC,id DESC);

CREATE TABLE IF NOT EXISTS public.hr_employee_record_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    record_type varchar(32) NOT NULL
        CHECK (record_type IN ('emergency_contact','employment_history')),
    record_id bigint NOT NULL,
    event_type varchar(32) NOT NULL
        CHECK (event_type IN ('created','updated','deactivated')),
    before_state jsonb NOT NULL DEFAULT '{}'::jsonb,
    after_state jsonb NOT NULL DEFAULT '{}'::jsonb,
    actor_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (jsonb_typeof(before_state)='object' AND jsonb_typeof(after_state)='object')
);
CREATE INDEX IF NOT EXISTS hr_employee_record_events_employee_idx
    ON public.hr_employee_record_events(employee_id,created_at,id);

CREATE OR REPLACE FUNCTION public.guard_hr_employee_immutable_history()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Employee employment history and record audit events are append-only';
END;
$$;
DROP TRIGGER IF EXISTS trg_hr_employee_employment_history_immutable
    ON public.hr_employee_employment_history;
CREATE TRIGGER trg_hr_employee_employment_history_immutable
    BEFORE UPDATE OR DELETE ON public.hr_employee_employment_history
    FOR EACH ROW EXECUTE FUNCTION public.guard_hr_employee_immutable_history();
DROP TRIGGER IF EXISTS trg_hr_employee_record_events_immutable
    ON public.hr_employee_record_events;
CREATE TRIGGER trg_hr_employee_record_events_immutable
    BEFORE UPDATE OR DELETE ON public.hr_employee_record_events
    FOR EACH ROW EXECUTE FUNCTION public.guard_hr_employee_immutable_history();

