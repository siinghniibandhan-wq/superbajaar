-- Additive Warehouse/Fulfilment persistence. Inventory remains the stock ledger.
CREATE TABLE IF NOT EXISTS public.fulfilment_pick_tasks (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shipment_id bigint NOT NULL UNIQUE REFERENCES public.deliveries(id) ON DELETE RESTRICT,
 order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE RESTRICT,
 status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','in_progress','short','completed','cancelled')),
 assigned_to_user_id bigint REFERENCES public.app_users(id) ON DELETE RESTRICT,
 assigned_to_name varchar(200),
 started_at timestamptz, completed_at timestamptz,
 created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE RESTRICT,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_fulfilment_pick_queue ON public.fulfilment_pick_tasks(status,created_at DESC);

CREATE TABLE IF NOT EXISTS public.fulfilment_pick_task_lines (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pick_task_id bigint NOT NULL REFERENCES public.fulfilment_pick_tasks(id) ON DELETE RESTRICT,
 order_line_id bigint NOT NULL REFERENCES public.order_lines(id) ON DELETE RESTRICT,
 variant_id bigint NOT NULL REFERENCES public.product_variants(id) ON DELETE RESTRICT,
 location_id bigint NOT NULL REFERENCES public.stock_locations(id) ON DELETE RESTRICT,
 requested_quantity numeric(14,3) NOT NULL CHECK(requested_quantity>0),
 picked_quantity numeric(14,3) NOT NULL DEFAULT 0 CHECK(picked_quantity>=0),
 short_quantity numeric(14,3) NOT NULL DEFAULT 0 CHECK(short_quantity>=0),
 short_reason text,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(pick_task_id,order_line_id,location_id),
 CHECK(picked_quantity+short_quantity<=requested_quantity)
);

CREATE TABLE IF NOT EXISTS public.fulfilment_packages (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shipment_id bigint NOT NULL REFERENCES public.deliveries(id) ON DELETE RESTRICT,
 package_number varchar(60) NOT NULL,
 status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','sealed','dispatched','cancelled')),
 weight_grams numeric(12,2) CHECK(weight_grams IS NULL OR weight_grams>0),
 length_mm numeric(12,2) CHECK(length_mm IS NULL OR length_mm>0),
 width_mm numeric(12,2) CHECK(width_mm IS NULL OR width_mm>0),
 height_mm numeric(12,2) CHECK(height_mm IS NULL OR height_mm>0),
 sealed_at timestamptz,
 created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE RESTRICT,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(shipment_id,package_number)
);

CREATE TABLE IF NOT EXISTS public.fulfilment_package_lines (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 package_id bigint NOT NULL REFERENCES public.fulfilment_packages(id) ON DELETE RESTRICT,
 pick_task_line_id bigint NOT NULL REFERENCES public.fulfilment_pick_task_lines(id) ON DELETE RESTRICT,
 order_line_id bigint NOT NULL REFERENCES public.order_lines(id) ON DELETE RESTRICT,
 variant_id bigint NOT NULL REFERENCES public.product_variants(id) ON DELETE RESTRICT,
 quantity numeric(14,3) NOT NULL CHECK(quantity>0),
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(package_id,order_line_id)
);

CREATE TABLE IF NOT EXISTS public.fulfilment_dispatch_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shipment_id bigint NOT NULL REFERENCES public.deliveries(id) ON DELETE RESTRICT,
 dispatch_id uuid NOT NULL,
 payload_hash char(64) NOT NULL CHECK(payload_hash ~ '^[0-9a-f]{64}$'),
 actor_user_id bigint REFERENCES public.app_users(id) ON DELETE RESTRICT,
 actor_email varchar(254) NOT NULL,
 note text, created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(shipment_id,dispatch_id)
);
CREATE TABLE IF NOT EXISTS public.fulfilment_dispatch_event_lines (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dispatch_event_id bigint NOT NULL REFERENCES public.fulfilment_dispatch_events(id) ON DELETE RESTRICT,
 package_id bigint REFERENCES public.fulfilment_packages(id) ON DELETE RESTRICT,
 order_line_id bigint NOT NULL REFERENCES public.order_lines(id) ON DELETE RESTRICT,
 variant_id bigint NOT NULL REFERENCES public.product_variants(id) ON DELETE RESTRICT,
 inventory_movement_id bigint NOT NULL REFERENCES public.inventory_movements(id) ON DELETE RESTRICT,
 quantity numeric(14,3) NOT NULL CHECK(quantity>0),
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(dispatch_event_id,inventory_movement_id)
);

CREATE TABLE IF NOT EXISTS public.fulfilment_returns (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 return_number varchar(50) NOT NULL UNIQUE,
 shipment_id bigint NOT NULL REFERENCES public.deliveries(id) ON DELETE RESTRICT,
 order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE RESTRICT,
 status text NOT NULL DEFAULT 'requested' CHECK(status IN ('requested','authorised','received','inspection','approved','rejected','closed')),
 reason text NOT NULL CHECK(length(btrim(reason))>=3),
 requested_by_user_id bigint REFERENCES public.app_users(id) ON DELETE RESTRICT,
 received_by_user_id bigint REFERENCES public.app_users(id) ON DELETE RESTRICT,
 received_at timestamptz, closed_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_fulfilment_returns_queue ON public.fulfilment_returns(status,created_at DESC);

CREATE TABLE IF NOT EXISTS public.fulfilment_return_lines (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 return_id bigint NOT NULL REFERENCES public.fulfilment_returns(id) ON DELETE RESTRICT,
 order_line_id bigint NOT NULL REFERENCES public.order_lines(id) ON DELETE RESTRICT,
 variant_id bigint NOT NULL REFERENCES public.product_variants(id) ON DELETE RESTRICT,
 requested_quantity numeric(14,3) NOT NULL CHECK(requested_quantity>0),
 received_quantity numeric(14,3) NOT NULL DEFAULT 0 CHECK(received_quantity>=0),
 inspection_status text NOT NULL DEFAULT 'pending' CHECK(inspection_status IN ('pending','accepted','rejected','damaged','quarantined')),
 disposition text CHECK(disposition IS NULL OR disposition IN ('restock','write_off','quarantine','repair')),
 inventory_movement_id bigint REFERENCES public.inventory_movements(id) ON DELETE RESTRICT,
 inspection_note text,
 inspected_by_user_id bigint REFERENCES public.app_users(id) ON DELETE RESTRICT,
 inspected_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(return_id,order_line_id),
 CHECK(received_quantity<=requested_quantity),
 CHECK(disposition IS NULL OR inspection_status IN ('accepted','rejected','damaged','quarantined')),
 CHECK(disposition IS DISTINCT FROM 'restock' OR inventory_movement_id IS NOT NULL)
);

-- Dispatch events are immutable evidence; corrections use a new dispatch identity.
CREATE OR REPLACE FUNCTION public.guard_fulfilment_dispatch_evidence()
RETURNS trigger
LANGUAGE plpgsql
AS $fulfilment_guard$
BEGIN
    RAISE EXCEPTION 'Fulfilment dispatch evidence is immutable';
END;
$fulfilment_guard$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname='fulfilment_dispatch_events_immutable_trg'
          AND tgrelid='public.fulfilment_dispatch_events'::regclass
    ) THEN
        CREATE TRIGGER fulfilment_dispatch_events_immutable_trg
        BEFORE UPDATE OR DELETE ON public.fulfilment_dispatch_events
        FOR EACH ROW EXECUTE FUNCTION public.guard_fulfilment_dispatch_evidence();
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname='fulfilment_dispatch_event_lines_immutable_trg'
          AND tgrelid='public.fulfilment_dispatch_event_lines'::regclass
    ) THEN
        CREATE TRIGGER fulfilment_dispatch_event_lines_immutable_trg
        BEFORE UPDATE OR DELETE ON public.fulfilment_dispatch_event_lines
        FOR EACH ROW EXECUTE FUNCTION public.guard_fulfilment_dispatch_evidence();
    END IF;
END
$$;

DO $grant$
BEGIN
 IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='superbajaar_user') THEN
  GRANT SELECT,INSERT,UPDATE ON public.fulfilment_pick_tasks,public.fulfilment_pick_task_lines,public.fulfilment_packages,public.fulfilment_package_lines,public.fulfilment_returns,public.fulfilment_return_lines TO superbajaar_user;
  GRANT SELECT,INSERT ON public.fulfilment_dispatch_events,public.fulfilment_dispatch_event_lines TO superbajaar_user;
  GRANT USAGE,SELECT ON SEQUENCE public.fulfilment_pick_tasks_id_seq,public.fulfilment_pick_task_lines_id_seq,public.fulfilment_packages_id_seq,public.fulfilment_package_lines_id_seq,public.fulfilment_dispatch_events_id_seq,public.fulfilment_dispatch_event_lines_id_seq,public.fulfilment_returns_id_seq,public.fulfilment_return_lines_id_seq TO superbajaar_user;
 END IF;
END $grant$;


-- Dispatch event evidence is append-only. Corrections require a compensating
-- event; existing event identity, payload and movement links are never edited.
CREATE OR REPLACE FUNCTION public.guard_fulfilment_dispatch_evidence()
RETURNS trigger
LANGUAGE plpgsql
AS $fulfilment_dispatch_guard$
BEGIN
    RAISE EXCEPTION 'Fulfilment dispatch evidence is immutable';
END;
$fulfilment_dispatch_guard$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname='fulfilment_dispatch_events_immutable_trg'
          AND tgrelid='public.fulfilment_dispatch_events'::regclass
    ) THEN
        CREATE TRIGGER fulfilment_dispatch_events_immutable_trg
        BEFORE UPDATE OR DELETE ON public.fulfilment_dispatch_events
        FOR EACH ROW EXECUTE FUNCTION public.guard_fulfilment_dispatch_evidence();
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname='fulfilment_dispatch_event_lines_immutable_trg'
          AND tgrelid='public.fulfilment_dispatch_event_lines'::regclass
    ) THEN
        CREATE TRIGGER fulfilment_dispatch_event_lines_immutable_trg
        BEFORE UPDATE OR DELETE ON public.fulfilment_dispatch_event_lines
        FOR EACH ROW EXECUTE FUNCTION public.guard_fulfilment_dispatch_evidence();
    END IF;
END
$$;
