-- Integrated HRMS business workflows (recruitment through workforce analytics).
-- Domain payloads are versioned JSONB so each workflow can evolve without destructive
-- schema changes; immutable events retain a complete audit trail.
CREATE TABLE IF NOT EXISTS public.hr_enterprise_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain text NOT NULL CHECK (domain IN
      ('recruitment','documents','performance','learning','assets','travel','exit','analytics')),
    employee_id bigint REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    parent_id bigint REFERENCES public.hr_enterprise_records(id) ON DELETE RESTRICT,
    title text NOT NULL CHECK (length(trim(title)) > 0),
    status text NOT NULL,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(payload)='object'),
    effective_date date,
    due_date date,
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    updated_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    version integer NOT NULL DEFAULT 1 CHECK (version > 0)
);
CREATE INDEX IF NOT EXISTS hr_enterprise_domain_status_idx
  ON public.hr_enterprise_records(domain,status,updated_at DESC);
CREATE INDEX IF NOT EXISTS hr_enterprise_employee_domain_idx
  ON public.hr_enterprise_records(employee_id,domain,created_at DESC);
CREATE INDEX IF NOT EXISTS hr_enterprise_parent_idx
  ON public.hr_enterprise_records(parent_id) WHERE parent_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS hr_enterprise_due_idx
  ON public.hr_enterprise_records(domain,due_date) WHERE due_date IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.hr_enterprise_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id bigint NOT NULL REFERENCES public.hr_enterprise_records(id) ON DELETE RESTRICT,
    event_type text NOT NULL,
    from_status text,
    to_status text,
    before_state jsonb,
    after_state jsonb,
    note text,
    actor_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS hr_enterprise_events_record_idx
  ON public.hr_enterprise_events(record_id,created_at DESC);

CREATE OR REPLACE FUNCTION public.hr_enterprise_immutable_event()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'HR enterprise audit events are immutable';
END;
$$;
DROP TRIGGER IF EXISTS hr_enterprise_events_no_update ON public.hr_enterprise_events;
CREATE TRIGGER hr_enterprise_events_no_update BEFORE UPDATE OR DELETE
  ON public.hr_enterprise_events FOR EACH ROW EXECUTE FUNCTION public.hr_enterprise_immutable_event();

-- Preserve audit history: records are archived, never physically deleted.
CREATE OR REPLACE FUNCTION public.hr_enterprise_no_delete()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'HR enterprise records cannot be deleted; archive them instead';
END;
$$;
DROP TRIGGER IF EXISTS hr_enterprise_records_no_delete ON public.hr_enterprise_records;
CREATE TRIGGER hr_enterprise_records_no_delete BEFORE DELETE
  ON public.hr_enterprise_records FOR EACH ROW EXECUTE FUNCTION public.hr_enterprise_no_delete();

