-- Shared invitation-only access foundation for Vendor and Employee portals.
-- Additive only. Existing app_users, sessions, suppliers and HR employee identities are reused.

CREATE TABLE IF NOT EXISTS public.portal_invitations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portal_type text NOT NULL CHECK (portal_type IN ('vendor','employee')),
    email text NOT NULL,
    supplier_id bigint REFERENCES public.suppliers(id) ON DELETE RESTRICT,
    employee_id bigint REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    token_hash char(64) NOT NULL UNIQUE,
    expires_at timestamptz NOT NULL,
    accepted_at timestamptz,
    revoked_at timestamptz,
    invited_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (
        (portal_type='vendor' AND supplier_id IS NOT NULL AND employee_id IS NULL)
        OR
        (portal_type='employee' AND employee_id IS NOT NULL AND supplier_id IS NULL)
    ),
    CHECK (length(trim(email)) > 3),
    CHECK (accepted_at IS NULL OR revoked_at IS NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS portal_invitations_one_pending_email_idx
    ON public.portal_invitations(lower(email))
    WHERE accepted_at IS NULL AND revoked_at IS NULL;
\nCREATE INDEX IF NOT EXISTS portal_invitations_email_idx
    ON public.portal_invitations(portal_type,lower(email),created_at DESC);
CREATE INDEX IF NOT EXISTS portal_invitations_supplier_idx
    ON public.portal_invitations(supplier_id,created_at DESC)
    WHERE supplier_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS portal_invitations_employee_idx
    ON public.portal_invitations(employee_id,created_at DESC)
    WHERE employee_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.vendor_portal_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
    supplier_id bigint NOT NULL REFERENCES public.suppliers(id) ON DELETE RESTRICT,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(user_id,supplier_id)
);
CREATE INDEX IF NOT EXISTS vendor_portal_users_supplier_idx
    ON public.vendor_portal_users(supplier_id,is_active);

