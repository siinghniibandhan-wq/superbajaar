CREATE TABLE IF NOT EXISTS public.vendor_purchase_order_responses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id bigint NOT NULL REFERENCES public.purchase_orders(id) ON DELETE RESTRICT,
    supplier_id bigint NOT NULL REFERENCES public.suppliers(id) ON DELETE RESTRICT,
    response text NOT NULL CHECK (response IN ('accepted','rejected')),
    note text,
    responded_by_user_id bigint NOT NULL REFERENCES public.app_users(id) ON DELETE RESTRICT,
    responded_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(purchase_order_id)
);
CREATE INDEX IF NOT EXISTS vendor_po_response_supplier_idx
    ON public.vendor_purchase_order_responses(supplier_id,responded_at DESC);
