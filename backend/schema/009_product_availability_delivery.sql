-- Product sales-channel and delivery configuration.
-- Idempotent additive migration; does not rewrite existing product data.
ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS is_pos_available boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS is_website_available boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS delivery_options text[] NOT NULL DEFAULT ARRAY['standard']::text[];

CREATE TABLE IF NOT EXISTS public.product_availability_rules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  channel text NOT NULL CHECK (channel IN ('pos', 'website')),
  region_code text,
  pincode char(6),
  location_id bigint REFERENCES public.stock_locations(id) ON DELETE RESTRICT,
  is_allowed boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT product_availability_rules_pincode_check CHECK (pincode IS NULL OR pincode ~ '^[0-9]{6}$'),
  CONSTRAINT product_availability_rules_scope_check CHECK (region_code IS NOT NULL OR pincode IS NOT NULL OR location_id IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_product_availability_rules_product
  ON public.product_availability_rules(product_id, channel);
