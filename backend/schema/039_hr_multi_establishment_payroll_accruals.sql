-- Store one payroll accrual journal per legal establishment.
-- The legacy single-voucher column remains populated for one-establishment runs.

CREATE TABLE IF NOT EXISTS public.hr_payroll_accrual_postings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payroll_run_id bigint NOT NULL REFERENCES public.hr_payroll_runs(id) ON DELETE RESTRICT,
    establishment_id bigint NOT NULL REFERENCES public.hr_establishments(id) ON DELETE RESTRICT,
    accounting_voucher_id bigint NOT NULL UNIQUE REFERENCES public.accounting_vouchers(id) ON DELETE RESTRICT,
    total_amount numeric(16,2) NOT NULL CHECK (total_amount > 0),
    posted_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(payroll_run_id,establishment_id)
);

CREATE INDEX IF NOT EXISTS hr_payroll_accrual_postings_run_idx
    ON public.hr_payroll_accrual_postings(payroll_run_id,establishment_id);

DO $grants$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='superbajaar_user') THEN
        GRANT SELECT,INSERT ON public.hr_payroll_accrual_postings TO superbajaar_user;
        GRANT USAGE,SELECT ON SEQUENCE public.hr_payroll_accrual_postings_id_seq TO superbajaar_user;
    END IF;
END
$grants$;
