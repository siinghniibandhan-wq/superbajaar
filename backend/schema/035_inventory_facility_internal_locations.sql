-- 035: additive facility metadata and internal warehouse-location hierarchy.
-- Existing stock_locations IDs remain the canonical facility references used by
-- inventory, purchasing, accounting, approvals and fulfilment.

ALTER TABLE public.stock_locations
    ADD COLUMN IF NOT EXISTS address_line1 varchar(200),
    ADD COLUMN IF NOT EXISTS address_line2 varchar(200),
    ADD COLUMN IF NOT EXISTS city varchar(100),
    ADD COLUMN IF NOT EXISTS district varchar(100),
    ADD COLUMN IF NOT EXISTS state varchar(100),
    ADD COLUMN IF NOT EXISTS region_code varchar(32);

CREATE TABLE IF NOT EXISTS public.stock_internal_locations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_id bigint NOT NULL REFERENCES public.stock_locations(id) ON DELETE RESTRICT,
    parent_id bigint,
    code varchar(40) NOT NULL,
    name varchar(120) NOT NULL,
    location_type varchar(16) NOT NULL
        CHECK (location_type IN ('receiving','storage','rack','shelf','bin','picking','packing','dispatch','quarantine','repair')),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(code)) > 0),
    CHECK (length(trim(name)) > 0),
    CHECK (parent_id IS NULL OR parent_id <> id),
    UNIQUE (facility_id, code),
    UNIQUE (id, facility_id),
    CONSTRAINT stock_internal_locations_parent_same_facility_fk
        FOREIGN KEY (parent_id, facility_id)
        REFERENCES public.stock_internal_locations(id, facility_id)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS stock_internal_locations_facility_active_idx
    ON public.stock_internal_locations(facility_id, is_active, code);
CREATE INDEX IF NOT EXISTS stock_internal_locations_parent_idx
    ON public.stock_internal_locations(parent_id) WHERE parent_id IS NOT NULL;

DO $grant$
