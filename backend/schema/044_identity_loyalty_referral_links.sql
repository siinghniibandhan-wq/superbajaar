-- 044: Additive links for invitation representatives, loyalty and referral identities.
-- No existing account, card, balance, ledger, referral code or reward is rewritten.

ALTER TABLE public.portal_invitations
    ADD COLUMN IF NOT EXISTS representative_name text;

CREATE TABLE IF NOT EXISTS public.identity_loyalty_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id bigint NOT NULL REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    loyalty_account_id bigint NOT NULL REFERENCES public.loyalty_accounts(id) ON DELETE RESTRICT,
    link_method text NOT NULL CHECK (link_method IN ('verified_customer_account','admin_verified')),
    linked_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    linked_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (loyalty_account_id),
    UNIQUE (party_id, loyalty_account_id)
);
CREATE INDEX IF NOT EXISTS identity_loyalty_party_idx
    ON public.identity_loyalty_accounts(party_id, linked_at DESC);

CREATE TABLE IF NOT EXISTS public.identity_referral_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referral_id bigint NOT NULL UNIQUE REFERENCES public.customer_referrals(id) ON DELETE RESTRICT,
    referrer_party_id bigint NOT NULL REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    referred_party_id bigint NOT NULL REFERENCES public.identity_parties(id) ON DELETE RESTRICT,
    linked_at timestamptz NOT NULL DEFAULT now(),
    CHECK (referrer_party_id <> referred_party_id)
);
CREATE INDEX IF NOT EXISTS identity_referral_referrer_idx
    ON public.identity_referral_links(referrer_party_id, linked_at DESC);
CREATE INDEX IF NOT EXISTS identity_referral_referred_idx
    ON public.identity_referral_links(referred_party_id, linked_at DESC);

