        GRANT USAGE,SELECT ON SEQUENCE public.identity_loyalty_accounts_id_seq,public.identity_referral_links_id_seq TO superbajaar_user;
        GRANT SELECT,UPDATE ON public.portal_invitations TO superbajaar_user;
    END IF;
END $$;
