-- Proposed baseline from the user-provided live sb_app schema-only pg_dump (PostgreSQL 15.19).
-- Draft for review only. No data is included. No BEGIN/COMMIT or SET ROLE.
-- orders.customer_email is intentionally omitted; the follow-up schema migration adds it.
-- Every table and index uses IF NOT EXISTS. Constraint definitions are embedded in CREATE TABLE.
-- WARNING: CREATE TABLE IF NOT EXISTS does not reconcile a pre-existing table with a different definition.

CREATE SEQUENCE IF NOT EXISTS public.orders_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
CREATE SEQUENCE IF NOT EXISTS public.products_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
CREATE SEQUENCE IF NOT EXISTS public.order_items_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
CREATE SEQUENCE IF NOT EXISTS public.price_history_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
CREATE SEQUENCE IF NOT EXISTS public.tickets_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
CREATE SEQUENCE IF NOT EXISTS public.users_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;

CREATE TABLE IF NOT EXISTS public.app_users (
 id bigint GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME public.app_users_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1) NOT NULL,
 email text NOT NULL, full_name text NOT NULL, password_hash text NOT NULL,
 role text DEFAULT 'staff'::text NOT NULL, is_active boolean DEFAULT true NOT NULL,
 created_at timestamp with time zone DEFAULT now() NOT NULL, updated_at timestamp with time zone DEFAULT now() NOT NULL,
 CONSTRAINT app_users_pkey PRIMARY KEY (id), CONSTRAINT app_users_email_key UNIQUE (email),
 CONSTRAINT app_users_full_name_check CHECK (length(TRIM(BOTH FROM full_name)) > 0),
 CONSTRAINT app_users_role_check CHECK (role = ANY (ARRAY['owner'::text,'admin'::text,'manager'::text,'staff'::text,'viewer'::text]))
);

