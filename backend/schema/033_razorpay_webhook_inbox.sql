-- 033: Razorpay payment references and durable webhook inbox.
-- Additive and idempotent; no existing payment/order data is rewritten.

ALTER TABLE public.payments
    ADD COLUMN IF NOT EXISTS provider_order_id varchar(100),
    ADD COLUMN IF NOT EXISTS currency char(3) NOT NULL DEFAULT 'INR';

CREATE UNIQUE INDEX IF NOT EXISTS payments_provider_order_id_uidx
    ON public.payments(provider_order_id)
    WHERE provider_order_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.payment_provider_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider text NOT NULL CHECK (provider IN ('razorpay')),
    provider_event_id varchar(200) NOT NULL,
    event_type varchar(120) NOT NULL,
    payload_sha256 char(64) NOT NULL CHECK (payload_sha256 ~ '^[0-9a-f]{64}$'),
    processing_status text NOT NULL DEFAULT 'received'
        CHECK (processing_status IN ('received','processed','ignored','failed')),
    payment_id bigint REFERENCES public.payments(id) ON DELETE RESTRICT,
    received_at timestamptz NOT NULL DEFAULT now(),
    processed_at timestamptz,
    UNIQUE(provider, provider_event_id)
);

CREATE INDEX IF NOT EXISTS payment_provider_events_status_idx
    ON public.payment_provider_events(processing_status, received_at);

DO $grant$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='superbajaar_user') THEN
        GRANT SELECT, INSERT, UPDATE ON public.payment_provider_events TO superbajaar_user;
        GRANT USAGE, SELECT ON SEQUENCE public.payment_provider_events_id_seq TO superbajaar_user;
        GRANT SELECT, INSERT, UPDATE ON public.payments TO superbajaar_user;
    END IF;
END
$grant$;
