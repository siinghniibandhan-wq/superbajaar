-- Approved overtime, incentives and bonuses included in monthly payroll.
-- No default overtime rates or incentive formulas are assumed.

CREATE TABLE IF NOT EXISTS public.hr_payroll_earning_adjustments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    earning_type text NOT NULL CHECK (earning_type IN ('overtime','incentive','bonus')),
    period_start date NOT NULL,
    period_end date NOT NULL,
    amount numeric(14,2) NOT NULL CHECK (amount > 0),
    hours numeric(8,2),
    hourly_rate numeric(14,2),
    reason text NOT NULL,
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
    review_note text,
    payroll_run_id bigint REFERENCES public.hr_payroll_runs(id) ON DELETE RESTRICT,
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    reviewed_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (period_start = date_trunc('month',period_start)::date),
    CHECK (period_end = (date_trunc('month',period_start) + interval '1 month - 1 day')::date),
    CHECK (length(trim(reason)) >= 5),
    CHECK ((hours IS NULL AND hourly_rate IS NULL) OR (hours > 0 AND hourly_rate > 0)),
    CHECK (
        (earning_type='overtime' AND hours IS NOT NULL AND hourly_rate IS NOT NULL
            AND amount=round(hours*hourly_rate,2))
        OR (earning_type<>'overtime' AND hours IS NULL AND hourly_rate IS NULL)
    ),
    CHECK ((status='pending' AND reviewed_at IS NULL AND reviewed_by_user_id IS NULL AND payroll_run_id IS NULL)
        OR (status='rejected' AND reviewed_at IS NOT NULL AND reviewed_by_user_id IS NOT NULL AND payroll_run_id IS NULL)
        OR (status='approved' AND reviewed_at IS NOT NULL AND reviewed_by_user_id IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS hr_payroll_earning_period_idx
    ON public.hr_payroll_earning_adjustments(period_start,period_end,status,employee_id);
CREATE INDEX IF NOT EXISTS hr_payroll_earning_run_idx
    ON public.hr_payroll_earning_adjustments(payroll_run_id)
    WHERE payroll_run_id IS NOT NULL;

