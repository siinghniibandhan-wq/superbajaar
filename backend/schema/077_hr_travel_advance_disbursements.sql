-- 077: idempotent travel advance disbursement links to posted accounting vouchers.
CREATE TABLE IF NOT EXISTS public.hr_travel_advance_disbursements (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 enterprise_record_id bigint NOT NULL UNIQUE REFERENCES public.hr_enterprise_records(id) ON DELETE RESTRICT,
 employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
 accounting_voucher_id bigint NOT NULL UNIQUE REFERENCES public.accounting_vouchers(id) ON DELETE RESTRICT,
 amount numeric(14,2) NOT NULL CHECK(amount>0),
 currency char(3) NOT NULL DEFAULT 'INR',
 disbursed_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
 disbursed_at timestamptz NOT NULL DEFAULT now()
);
DO $grants$
BEGIN
 IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='superbajaar_user') THEN
  GRANT SELECT,INSERT ON public.hr_travel_advance_disbursements TO superbajaar_user;
  GRANT USAGE,SELECT ON SEQUENCE public.hr_travel_advance_disbursements_id_seq TO superbajaar_user;
 END IF;
END
$grants$;
