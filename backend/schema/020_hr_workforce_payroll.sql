-- HR, attendance, leave, reimbursements and payroll foundation.
-- Additive/idempotent; links workforce identities to the existing staff auth system.
CREATE TABLE IF NOT EXISTS public.hr_departments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL UNIQUE,
    description text,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(code)) > 0),
    CHECK (length(trim(name)) > 0)
);

CREATE TABLE IF NOT EXISTS public.hr_employees (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint UNIQUE REFERENCES public.app_users(id) ON DELETE SET NULL,
    employee_code text NOT NULL UNIQUE,
    first_name text NOT NULL,
    last_name text NOT NULL DEFAULT '',
    email text NOT NULL UNIQUE,
    phone text NOT NULL DEFAULT '',
    department_id bigint REFERENCES public.hr_departments(id) ON DELETE SET NULL,
    designation text NOT NULL,
    reports_to_employee_id bigint REFERENCES public.hr_employees(id) ON DELETE SET NULL,
    employment_type text NOT NULL DEFAULT 'full_time'
        CHECK (employment_type IN ('full_time','part_time','contract','intern','shift_worker')),
    status text NOT NULL DEFAULT 'active'
        CHECK (status IN ('active','probation','on_leave','notice_period','terminated')),
    joining_date date NOT NULL,
    exit_date date,
    basic_salary numeric(14,2) NOT NULL DEFAULT 0 CHECK (basic_salary >= 0),
    hra numeric(14,2) NOT NULL DEFAULT 0 CHECK (hra >= 0),
    special_allowance numeric(14,2) NOT NULL DEFAULT 0 CHECK (special_allowance >= 0),
    other_allowance numeric(14,2) NOT NULL DEFAULT 0 CHECK (other_allowance >= 0),
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (exit_date IS NULL OR exit_date >= joining_date),
    CHECK (length(trim(employee_code)) > 0),
    CHECK (length(trim(first_name)) > 0),
    CHECK (length(trim(email)) > 0),
    CHECK (length(trim(designation)) > 0)
);
CREATE INDEX IF NOT EXISTS hr_employees_department_status_idx
    ON public.hr_employees(department_id,status);
CREATE INDEX IF NOT EXISTS hr_employees_user_idx
    ON public.hr_employees(user_id) WHERE user_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.hr_attendance_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    clock_in_at timestamptz NOT NULL DEFAULT now(),
    clock_out_at timestamptz,
    clock_in_note text,
    clock_out_note text,
    source text NOT NULL DEFAULT 'self_service' CHECK (source IN ('self_service','manager_adjustment','import')),
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    closed_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (clock_out_at IS NULL OR clock_out_at >= clock_in_at)
);
CREATE UNIQUE INDEX IF NOT EXISTS hr_attendance_one_open_session_idx
    ON public.hr_attendance_sessions(employee_id) WHERE clock_out_at IS NULL;
CREATE INDEX IF NOT EXISTS hr_attendance_employee_time_idx
    ON public.hr_attendance_sessions(employee_id,clock_in_at DESC);

CREATE TABLE IF NOT EXISTS public.hr_leave_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    leave_type text NOT NULL CHECK (leave_type IN ('annual','sick','casual','unpaid','other')),
    start_date date NOT NULL,
    end_date date NOT NULL,
    days numeric(6,2) NOT NULL CHECK (days > 0),
    reason text NOT NULL,
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','cancelled')),
    reviewed_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    review_note text,
    reviewed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (end_date >= start_date),
    CHECK (length(trim(reason)) > 0)
);
CREATE INDEX IF NOT EXISTS hr_leave_employee_dates_idx
    ON public.hr_leave_requests(employee_id,start_date,end_date);

CREATE TABLE IF NOT EXISTS public.hr_expenses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    category text NOT NULL,
    amount numeric(14,2) NOT NULL CHECK (amount > 0),
    expense_date date NOT NULL,
    description text NOT NULL,
    receipt_reference text,
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','reimbursed')),
    reviewed_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    review_note text,
    reviewed_at timestamptz,
    reimbursed_in_payroll_id bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(description)) > 0)
);
CREATE INDEX IF NOT EXISTS hr_expenses_employee_status_idx
    ON public.hr_expenses(employee_id,status,expense_date);

CREATE TABLE IF NOT EXISTS public.hr_payroll_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_start date NOT NULL,
    period_end date NOT NULL,
    status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','calculated','approved','paid','void')),
    currency char(3) NOT NULL DEFAULT 'INR' CHECK (currency = 'INR'),
    total_gross numeric(16,2) NOT NULL DEFAULT 0,
    total_deductions numeric(16,2) NOT NULL DEFAULT 0,
    total_reimbursements numeric(16,2) NOT NULL DEFAULT 0,
    total_net numeric(16,2) NOT NULL DEFAULT 0,
    accounting_voucher_id bigint REFERENCES public.accounting_vouchers(id) ON DELETE RESTRICT,
    notes text,
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    approved_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    approved_at timestamptz,
    paid_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (period_end >= period_start),
    UNIQUE(period_start,period_end)
);

CREATE TABLE IF NOT EXISTS public.hr_payslips (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payroll_run_id bigint NOT NULL REFERENCES public.hr_payroll_runs(id) ON DELETE RESTRICT,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    basic_salary numeric(14,2) NOT NULL CHECK (basic_salary >= 0),
    hra numeric(14,2) NOT NULL CHECK (hra >= 0),
    special_allowance numeric(14,2) NOT NULL CHECK (special_allowance >= 0),
    other_allowance numeric(14,2) NOT NULL CHECK (other_allowance >= 0),
    reimbursements numeric(14,2) NOT NULL DEFAULT 0 CHECK (reimbursements >= 0),
    gross_earnings numeric(14,2) NOT NULL CHECK (gross_earnings >= 0),
    deductions numeric(14,2) NOT NULL DEFAULT 0 CHECK (deductions >= 0),
    net_pay numeric(14,2) NOT NULL CHECK (net_pay >= 0),
    deduction_breakdown jsonb NOT NULL DEFAULT '{}'::jsonb,
    earnings_breakdown jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(payroll_run_id,employee_id)
);
CREATE INDEX IF NOT EXISTS hr_payslips_run_idx ON public.hr_payslips(payroll_run_id,employee_id);

ALTER TABLE public.hr_expenses
    DROP CONSTRAINT IF EXISTS hr_expenses_reimbursed_in_payroll_id_fkey;
ALTER TABLE public.hr_expenses
    ADD CONSTRAINT hr_expenses_reimbursed_in_payroll_id_fkey
    FOREIGN KEY (reimbursed_in_payroll_id) REFERENCES public.hr_payroll_runs(id) ON DELETE RESTRICT;

