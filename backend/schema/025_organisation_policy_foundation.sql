CREATE OR REPLACE FUNCTION public.guard_organisation_policy_history()
RETURNS trigger
LANGUAGE plpgsql
AS $policy_guard$
BEGIN
    IF TG_TABLE_NAME = 'organisation_policy_versions' THEN
        IF TG_OP = 'DELETE' THEN
            RAISE EXCEPTION 'Organisation policy versions cannot be deleted';
        END IF;
        IF OLD.status = 'retired' THEN
            RAISE EXCEPTION 'Retired organisation policy versions are immutable';
        END IF;
        IF OLD.status = 'active' AND (
            NEW.establishment_id IS DISTINCT FROM OLD.establishment_id OR
            NEW.domain IS DISTINCT FROM OLD.domain OR
            NEW.version_label IS DISTINCT FROM OLD.version_label OR
            NEW.effective_from IS DISTINCT FROM OLD.effective_from OR
            NEW.effective_to IS DISTINCT FROM OLD.effective_to OR
            NEW.policy_config IS DISTINCT FROM OLD.policy_config OR
            NEW.created_by_user_id IS DISTINCT FROM OLD.created_by_user_id OR
            NEW.activated_by_user_id IS DISTINCT FROM OLD.activated_by_user_id OR
            NEW.activated_at IS DISTINCT FROM OLD.activated_at OR
            NEW.created_at IS DISTINCT FROM OLD.created_at
        ) THEN
            RAISE EXCEPTION 'Active organisation policy configuration is immutable; create a new version';
        END IF;
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'Organisation policy audit and decision history is append-only';
END;
$policy_guard$;

DROP TRIGGER IF EXISTS trg_organisation_policy_version_guard ON public.organisation_policy_versions;
CREATE TRIGGER trg_organisation_policy_version_guard
    BEFORE UPDATE OR DELETE ON public.organisation_policy_versions
    FOR EACH ROW EXECUTE FUNCTION public.guard_organisation_policy_history();

DROP TRIGGER IF EXISTS trg_organisation_policy_audit_guard ON public.organisation_policy_audit_events;
CREATE TRIGGER trg_organisation_policy_audit_guard
    BEFORE UPDATE OR DELETE ON public.organisation_policy_audit_events
    FOR EACH ROW EXECUTE FUNCTION public.guard_organisation_policy_history();

