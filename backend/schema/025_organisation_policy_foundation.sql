        GRANT USAGE, SELECT ON SEQUENCE public.organisation_policy_audit_events_id_seq TO superbajaar_user;
        GRANT USAGE, SELECT ON SEQUENCE public.organisation_policy_decisions_id_seq TO superbajaar_user;
