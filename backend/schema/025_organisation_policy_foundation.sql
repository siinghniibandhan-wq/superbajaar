-- Organisation-scoped Purchase and Inventory policy foundation.
-- No approval bands, authority roles, shelf-life values or tolerances are seeded.
ALTER TABLE public.stock_locations
    ADD COLUMN IF NOT EXISTS establishment_id bigint;

DO $fk$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'stock_locations_establishment_id_fkey'
          AND conrelid = 'public.stock_locations'::regclass
    ) THEN
        ALTER TABLE public.stock_locations
            ADD CONSTRAINT stock_locations_establishment_id_fkey
            FOREIGN KEY (establishment_id)
            REFERENCES public.hr_establishments(id)
            ON DELETE RESTRICT;
    END IF;
END $fk$;

CREATE INDEX IF NOT EXISTS ix_stock_locations_establishment
    ON public.stock_locations(establishment_id)
    WHERE establishment_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.organisation_policy_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    establishment_id bigint NOT NULL REFERENCES public.hr_establishments(id) ON DELETE RESTRICT,
    domain text NOT NULL CHECK (domain IN ('purchase','inventory')),
    version_label text NOT NULL,
    effective_from date NOT NULL,
    effective_to date,
    policy_config jsonb NOT NULL,
    status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','active','retired')),
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    activated_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    activated_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(version_label)) > 0),
    CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CHECK (jsonb_typeof(policy_config) = 'object'),
    CHECK ((status = 'active' AND activated_by_user_id IS NOT NULL AND activated_at IS NOT NULL)
        OR status <> 'active')
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_organisation_policy_active_domain
    ON public.organisation_policy_versions(establishment_id,domain)
    WHERE status = 'active';
CREATE INDEX IF NOT EXISTS ix_organisation_policy_effective
    ON public.organisation_policy_versions(establishment_id,domain,effective_from,effective_to);

CREATE TABLE IF NOT EXISTS public.organisation_policy_audit_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_version_id bigint NOT NULL REFERENCES public.organisation_policy_versions(id) ON DELETE RESTRICT,
    event_type text NOT NULL CHECK (event_type IN ('created','validated','activated','retired')),
    actor_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    actor_email varchar(254) NOT NULL,
    actor_role varchar(100) NOT NULL,
    reason text,
    event_payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (jsonb_typeof(event_payload) = 'object')
);
CREATE INDEX IF NOT EXISTS ix_organisation_policy_audit
    ON public.organisation_policy_audit_events(policy_version_id,created_at,id);

CREATE TABLE IF NOT EXISTS public.organisation_policy_decisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_version_id bigint NOT NULL REFERENCES public.organisation_policy_versions(id) ON DELETE RESTRICT,
    establishment_id bigint NOT NULL REFERENCES public.hr_establishments(id) ON DELETE RESTRICT,
    domain text NOT NULL CHECK (domain IN ('purchase','inventory')),
    document_type text NOT NULL,
    document_id bigint NOT NULL CHECK (document_id > 0),
    document_revision integer NOT NULL DEFAULT 1 CHECK (document_revision > 0),
    stage_sequence integer NOT NULL CHECK (stage_sequence > 0),
    decision text NOT NULL CHECK (decision IN ('approved','rejected')),
    actor_user_id bigint NOT NULL REFERENCES public.app_users(id) ON DELETE RESTRICT,
    actor_email varchar(254) NOT NULL,
    actor_role varchar(100) NOT NULL,
    reason text NOT NULL,
    evaluation_snapshot jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(domain,document_type,document_id,document_revision,stage_sequence),
    CHECK (length(trim(reason)) > 0),
    CHECK (jsonb_typeof(evaluation_snapshot) = 'object')
);
CREATE INDEX IF NOT EXISTS ix_organisation_policy_decisions_document
    ON public.organisation_policy_decisions(domain,document_type,document_id,document_revision,stage_sequence);


