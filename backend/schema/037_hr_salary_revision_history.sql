-- Effective-dated salary revisions with manager approval and auditable reasons.
-- Existing employee salary fields are preserved and backfilled as the opening approved version.

CREATE TABLE IF NOT EXISTS public.hr_employee_salary_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    effective_from date NOT NULL,
    effective_to date,
    basic_salary numeric(14,2) NOT NULL CHECK (basic_salary >= 0),
    hra numeric(14,2) NOT NULL CHECK (hra >= 0),
    special_allowance numeric(14,2) NOT NULL CHECK (special_allowance >= 0),
    other_allowance numeric(14,2) NOT NULL CHECK (other_allowance >= 0),
    status text NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft','approved','rejected')),
    reason text NOT NULL,
    review_note text,
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    reviewed_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CHECK (length(trim(reason)) >= 5),
    CHECK ((status = 'approved' AND reviewed_at IS NOT NULL)
        OR status <> 'approved')
);

CREATE INDEX IF NOT EXISTS hr_employee_salary_versions_lookup_idx
    ON public.hr_employee_salary_versions(employee_id,effective_from DESC);
CREATE UNIQUE INDEX IF NOT EXISTS hr_employee_salary_versions_approved_start_idx
    ON public.hr_employee_salary_versions(employee_id,effective_from)
    WHERE status='approved';

-- Prevent overlapping approved salary periods. The employee row lock serializes
-- concurrent approvals for the same employee.
CREATE OR REPLACE FUNCTION public.guard_hr_employee_salary_version_period()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
    IF NEW.status = 'approved' THEN
        PERFORM 1 FROM public.hr_employees WHERE id=NEW.employee_id FOR UPDATE;
        IF EXISTS (
            SELECT 1
              FROM public.hr_employee_salary_versions v
             WHERE v.employee_id=NEW.employee_id
               AND v.status='approved'
               AND v.id IS DISTINCT FROM NEW.id
               AND daterange(v.effective_from,COALESCE(v.effective_to,'infinity'::date),'[]')
                   && daterange(NEW.effective_from,COALESCE(NEW.effective_to,'infinity'::date),'[]')
        ) THEN
            RAISE EXCEPTION 'Approved salary revision periods cannot overlap';
        END IF;
    END IF;
    RETURN NEW;
END;
$function$;

DO $guard$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
         WHERE tgrelid='public.hr_employee_salary_versions'::regclass
           AND tgname='trg_guard_hr_employee_salary_version_period'
           AND NOT tgisinternal
    ) THEN
        CREATE TRIGGER trg_guard_hr_employee_salary_version_period
        BEFORE INSERT OR UPDATE OF employee_id,effective_from,effective_to,status
        ON public.hr_employee_salary_versions
        FOR EACH ROW EXECUTE FUNCTION public.guard_hr_employee_salary_version_period();
    END IF;
END
$guard$;

-- Preserve the pre-existing salary profile as the opening approved version.
INSERT INTO public.hr_employee_salary_versions(
    employee_id,effective_from,basic_salary,hra,special_allowance,other_allowance,
    status,reason,reviewed_at
)
SELECT e.id,e.joining_date,e.basic_salary,e.hra,e.special_allowance,e.other_allowance,
       'approved','Opening salary profile imported from the existing employee record',now()
  FROM public.hr_employees e
 WHERE NOT EXISTS (
     SELECT 1 FROM public.hr_employee_salary_versions v
      WHERE v.employee_id=e.id AND v.status='approved'
 );

