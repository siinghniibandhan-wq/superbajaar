-- 034: HR shift scheduling, holiday calendars, leave policy ledger and lifecycle tasks.
-- Additive/idempotent. No entitlement values or statutory rates are pre-seeded.

CREATE TABLE IF NOT EXISTS public.hr_shift_definitions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    establishment_id bigint NOT NULL REFERENCES public.hr_establishments(id) ON DELETE RESTRICT,
    code varchar(32) NOT NULL,
    name varchar(120) NOT NULL,
    local_start_time time NOT NULL,
    local_end_time time NOT NULL,
    break_minutes integer NOT NULL DEFAULT 0 CHECK (break_minutes >= 0),
    timezone varchar(64) NOT NULL DEFAULT 'Asia/Kolkata',
    effective_from date NOT NULL,
    effective_to date,
    is_active boolean NOT NULL DEFAULT true,
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(code)) > 0),
    CHECK (length(trim(name)) > 0),
    CHECK (effective_to IS NULL OR effective_to >= effective_from),
    UNIQUE (establishment_id, code, effective_from)
);
CREATE INDEX IF NOT EXISTS hr_shift_definitions_active_idx
    ON public.hr_shift_definitions(establishment_id, is_active, effective_from, effective_to);

CREATE TABLE IF NOT EXISTS public.hr_shift_assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    shift_definition_id bigint NOT NULL REFERENCES public.hr_shift_definitions(id) ON DELETE RESTRICT,
    work_date date NOT NULL,
    planned_start_at timestamptz NOT NULL,
    planned_end_at timestamptz NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft','published','cancelled')),
    assigned_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    published_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    published_at timestamptz,
    cancellation_reason text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (planned_end_at > planned_start_at),
    CHECK ((status = 'published' AND published_by_user_id IS NOT NULL AND published_at IS NOT NULL)
        OR status <> 'published'),
    CHECK ((status = 'cancelled' AND length(trim(coalesce(cancellation_reason,''))) > 0)
        OR status <> 'cancelled')
);
CREATE UNIQUE INDEX IF NOT EXISTS hr_shift_one_active_assignment_per_day_idx
    ON public.hr_shift_assignments(employee_id, work_date) WHERE status IN ('draft','published');
CREATE INDEX IF NOT EXISTS hr_shift_assignments_roster_idx
    ON public.hr_shift_assignments(work_date, status, employee_id);

CREATE TABLE IF NOT EXISTS public.hr_holiday_calendars (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    establishment_id bigint NOT NULL REFERENCES public.hr_establishments(id) ON DELETE RESTRICT,
    name varchar(120) NOT NULL,
    region_code varchar(32),
    effective_year integer NOT NULL CHECK (effective_year BETWEEN 2000 AND 2200),
    status varchar(16) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','approved','retired')),
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    approved_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    approved_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(name)) > 0),
    CHECK ((status = 'approved' AND approved_by_user_id IS NOT NULL AND approved_at IS NOT NULL)
        OR status <> 'approved'),
    UNIQUE (establishment_id, name, effective_year)
);
CREATE INDEX IF NOT EXISTS hr_holiday_calendars_establishment_year_idx
    ON public.hr_holiday_calendars(establishment_id, effective_year, status);

CREATE TABLE IF NOT EXISTS public.hr_holidays (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_id bigint NOT NULL REFERENCES public.hr_holiday_calendars(id) ON DELETE RESTRICT,
    holiday_date date NOT NULL,
    name varchar(160) NOT NULL,
    holiday_type varchar(20) NOT NULL DEFAULT 'public'
        CHECK (holiday_type IN ('public','national','regional','optional','company')),
    location_code varchar(32),
    is_paid boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(name)) > 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS hr_holidays_calendar_date_location_uidx
    ON public.hr_holidays(calendar_id, holiday_date, coalesce(location_code,''));
CREATE INDEX IF NOT EXISTS hr_holidays_date_idx ON public.hr_holidays(calendar_id, holiday_date);

CREATE TABLE IF NOT EXISTS public.hr_leave_policies (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    establishment_id bigint NOT NULL REFERENCES public.hr_establishments(id) ON DELETE RESTRICT,
    leave_type varchar(20) NOT NULL CHECK (leave_type IN ('annual','sick','casual','unpaid','other')),
    version_label varchar(80) NOT NULL,
    effective_from date NOT NULL,
    effective_to date,
    entitlement_days numeric(7,2) NOT NULL DEFAULT 0 CHECK (entitlement_days >= 0),
    accrual_frequency varchar(16) NOT NULL DEFAULT 'none'
        CHECK (accrual_frequency IN ('none','monthly','quarterly','yearly')),
    carry_forward_cap numeric(7,2) NOT NULL DEFAULT 0 CHECK (carry_forward_cap >= 0),
    allow_negative_balance boolean NOT NULL DEFAULT false,
    encashment_allowed boolean NOT NULL DEFAULT false,
    probation_eligible boolean NOT NULL DEFAULT false,
    day_count_basis varchar(16) NOT NULL DEFAULT 'calendar'
        CHECK (day_count_basis IN ('calendar','working')),
    status varchar(16) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','approved','retired')),
    policy_notes text,
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    approved_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    approved_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(version_label)) > 0),
    CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CHECK ((status = 'approved' AND approved_by_user_id IS NOT NULL AND approved_at IS NOT NULL)
        OR status <> 'approved')
);
CREATE INDEX IF NOT EXISTS hr_leave_policies_effective_idx
    ON public.hr_leave_policies(establishment_id, leave_type, effective_from, effective_to, status);

CREATE TABLE IF NOT EXISTS public.hr_leave_balances (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    leave_type varchar(20) NOT NULL CHECK (leave_type IN ('annual','sick','casual','unpaid','other')),
    policy_id bigint NOT NULL REFERENCES public.hr_leave_policies(id) ON DELETE RESTRICT,
    period_start date NOT NULL,
    period_end date NOT NULL,
    opening_days numeric(9,2) NOT NULL DEFAULT 0,
    accrued_days numeric(9,2) NOT NULL DEFAULT 0,
    used_days numeric(9,2) NOT NULL DEFAULT 0,
    adjusted_days numeric(9,2) NOT NULL DEFAULT 0,
    closing_days numeric(9,2) NOT NULL DEFAULT 0,
    calculated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (period_end >= period_start),
    CHECK (opening_days >= 0 AND accrued_days >= 0 AND used_days >= 0),
    UNIQUE(employee_id, leave_type, policy_id, period_start, period_end)
);
CREATE INDEX IF NOT EXISTS hr_leave_balances_employee_period_idx
    ON public.hr_leave_balances(employee_id, period_end DESC);

CREATE TABLE IF NOT EXISTS public.hr_leave_ledger (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    leave_type varchar(20) NOT NULL CHECK (leave_type IN ('annual','sick','casual','unpaid','other')),
    policy_id bigint REFERENCES public.hr_leave_policies(id) ON DELETE RESTRICT,
    transaction_type varchar(20) NOT NULL
        CHECK (transaction_type IN ('opening','accrual','consumption','reversal','carry_forward','adjustment')),
    source_type varchar(24) NOT NULL
        CHECK (source_type IN ('policy_accrual','leave_request','manual_adjustment','carry_forward','opening_balance')),
    source_id bigint,
    effective_date date NOT NULL,
    quantity_days numeric(9,2) NOT NULL CHECK (quantity_days <> 0),
    reason text NOT NULL,
    actor_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(reason)) > 0),
    UNIQUE(employee_id, leave_type, transaction_type, source_type, source_id)
);
CREATE INDEX IF NOT EXISTS hr_leave_ledger_employee_date_idx
    ON public.hr_leave_ledger(employee_id, leave_type, effective_date, id);

CREATE TABLE IF NOT EXISTS public.hr_employee_lifecycle_templates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    establishment_id bigint REFERENCES public.hr_establishments(id) ON DELETE RESTRICT,
    name varchar(120) NOT NULL,
    lifecycle_type varchar(16) NOT NULL CHECK (lifecycle_type IN ('onboarding','offboarding')),
    version integer NOT NULL DEFAULT 1 CHECK (version > 0),
    is_active boolean NOT NULL DEFAULT true,
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(name)) > 0),
    UNIQUE(establishment_id, name, lifecycle_type, version)
);

CREATE TABLE IF NOT EXISTS public.hr_employee_lifecycle_template_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id bigint NOT NULL REFERENCES public.hr_employee_lifecycle_templates(id) ON DELETE RESTRICT,
    task_key varchar(64) NOT NULL,
    label varchar(180) NOT NULL,
    description text,
    owner_role varchar(24) NOT NULL DEFAULT 'manager'
        CHECK (owner_role IN ('employee','manager','hr','finance','it','admin')),
    due_days_offset integer NOT NULL DEFAULT 0,
    sequence integer NOT NULL DEFAULT 1 CHECK (sequence > 0),
    is_required boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(task_key)) > 0 AND length(trim(label)) > 0),
    UNIQUE(template_id, task_key)
);

CREATE TABLE IF NOT EXISTS public.hr_employee_lifecycle_tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id bigint NOT NULL REFERENCES public.hr_employees(id) ON DELETE RESTRICT,
    template_id bigint REFERENCES public.hr_employee_lifecycle_templates(id) ON DELETE RESTRICT,
    template_item_id bigint REFERENCES public.hr_employee_lifecycle_template_items(id) ON DELETE RESTRICT,
    task_key varchar(64) NOT NULL,
    label varchar(180) NOT NULL,
    description text,
    owner_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    due_date date,
    status varchar(16) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','in_progress','completed','waived','cancelled')),
    completed_at timestamptz,
    completed_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    evidence_reference varchar(500),
    completion_note text,
    created_by_user_id bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (length(trim(task_key)) > 0 AND length(trim(label)) > 0),
    CHECK ((status = 'completed' AND completed_at IS NOT NULL AND completed_by_user_id IS NOT NULL)
        OR status <> 'completed')
);
CREATE UNIQUE INDEX IF NOT EXISTS hr_lifecycle_task_template_item_uidx
    ON public.hr_employee_lifecycle_tasks(employee_id, template_item_id)
    WHERE template_item_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS hr_lifecycle_tasks_employee_status_idx
    ON public.hr_employee_lifecycle_tasks(employee_id, status, due_date);

