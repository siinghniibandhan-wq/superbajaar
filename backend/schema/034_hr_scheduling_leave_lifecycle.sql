CREATE OR REPLACE FUNCTION public.guard_hr_published_shift_history()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.status = 'published' THEN
            RAISE EXCEPTION 'Published shift assignments cannot be deleted';
        END IF;
        RETURN OLD;
    END IF;
    IF OLD.status = 'published' AND (
        NEW.employee_id IS DISTINCT FROM OLD.employee_id OR
        NEW.shift_definition_id IS DISTINCT FROM OLD.shift_definition_id OR
        NEW.work_date IS DISTINCT FROM OLD.work_date OR
        NEW.planned_start_at IS DISTINCT FROM OLD.planned_start_at OR
        NEW.planned_end_at IS DISTINCT FROM OLD.planned_end_at
    ) THEN
        RAISE EXCEPTION 'Published shift assignments cannot be rewritten; cancel and create a replacement';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_hr_published_shift_history ON public.hr_shift_assignments;
CREATE TRIGGER trg_hr_published_shift_history
    BEFORE UPDATE OR DELETE ON public.hr_shift_assignments
    FOR EACH ROW EXECUTE FUNCTION public.guard_hr_published_shift_history();

