CREATE OR REPLACE FUNCTION public.guard_hr_approved_reference_history()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME = 'hr_holiday_calendars' THEN
        IF TG_OP = 'DELETE' OR OLD.status IN ('approved','retired') THEN
            RAISE EXCEPTION 'Approved or retired holiday calendars are immutable';
        END IF;
    ELSIF TG_TABLE_NAME = 'hr_holidays' THEN
        IF TG_OP = 'DELETE' OR EXISTS (
            SELECT 1 FROM public.hr_holiday_calendars c
            WHERE c.id=OLD.calendar_id AND c.status IN ('approved','retired')
        ) THEN
            RAISE EXCEPTION 'Holidays in approved or retired calendars are immutable';
        END IF;
    ELSIF TG_TABLE_NAME = 'hr_leave_policies' THEN
        IF TG_OP = 'DELETE' OR OLD.status IN ('approved','retired') THEN
            RAISE EXCEPTION 'Approved or retired leave policies are immutable; create a new version';
        END IF;
    END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_hr_holiday_calendar_history ON public.hr_holiday_calendars;
CREATE TRIGGER trg_hr_holiday_calendar_history
    BEFORE UPDATE OR DELETE ON public.hr_holiday_calendars
    FOR EACH ROW EXECUTE FUNCTION public.guard_hr_approved_reference_history();
