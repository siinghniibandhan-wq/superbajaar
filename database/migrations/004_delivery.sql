-- Delivery tracking records; no carrier API is connected by this schema.
BEGIN;

CREATE TABLE IF NOT EXISTS deliveries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_reference TEXT NOT NULL UNIQUE,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
  delivery_pin CHAR(6) NOT NULL CHECK (delivery_pin ~ '^[0-9]{6}$'),
  recipient_name TEXT NOT NULL CHECK (length(trim(recipient_name)) > 0),
  recipient_phone TEXT NOT NULL,
  address TEXT NOT NULL CHECK (length(trim(address)) >= 5),
  location_id BIGINT REFERENCES stock_locations(id) ON DELETE RESTRICT,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','packed','assigned','dispatched','in_transit','delivered','failed','returned','cancelled')),
  tracking_reference TEXT,
  assigned_to TEXT,
  delivery_notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS delivery_status_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  delivery_id BIGINT NOT NULL REFERENCES deliveries(id) ON DELETE CASCADE,
  from_status TEXT,
  to_status TEXT NOT NULL,
  note TEXT,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_deliveries_status_created ON deliveries(status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_deliveries_order ON deliveries(order_id);

COMMIT;
