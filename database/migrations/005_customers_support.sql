-- Customer directory and customer support cases.
BEGIN;
CREATE TABLE IF NOT EXISTS customers(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL CHECK(length(trim(name))>0),
 phone TEXT UNIQUE,
 email TEXT UNIQUE,
 pin_code CHAR(6) CHECK(pin_code IS NULL OR pin_code ~ '^[0-9]{6}$'),
 address TEXT,
 notes TEXT,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_customers_name ON customers(name);
CREATE TABLE IF NOT EXISTS support_cases(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 case_number TEXT NOT NULL UNIQUE,
 customer_id BIGINT REFERENCES customers(id) ON DELETE SET NULL,
 order_id BIGINT REFERENCES orders(id) ON DELETE SET NULL,
 subject TEXT NOT NULL CHECK(length(trim(subject))>=3),
 description TEXT NOT NULL,
 priority TEXT NOT NULL DEFAULT 'normal' CHECK(priority IN ('low','normal','high','urgent')),
 status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','in_progress','waiting_customer','resolved','closed')),
 assigned_to TEXT,
 resolution TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_support_cases_status ON support_cases(status,created_at DESC);
COMMIT;
